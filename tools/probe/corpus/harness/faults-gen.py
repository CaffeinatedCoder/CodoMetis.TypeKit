# Generates tools/probe/corpus/harness/FaultClaimControllers.g.cs: the MVC controllers of the fault claims C04, C06, C14, C15
# and, from the same data, the table FaultClaim reads as the oracle's input (what each controller and action declares).
import sys

TS = ["one", "two", "dup", "decl"]
RET = {
    "one": "Results<NoContent, FaultProblem<HFault>>",
    "two": "Results<NoContent, FaultProblem<HFault>, FaultProblem<GFault>>",
    "dup": "Results<NoContent, FaultProblem<HFault>, FaultProblem<KFault>>",
    "decl": "Results<NoContent, FaultProblem<HFault>>",
}
BODY = {"one": "FxErr.One(e)", "two": "FxErr.Two(e)", "dup": "FxErr.Dup(e)", "decl": "FxErr.One(e)"}

# decl: (type, member, status); status 0 = left out
def attr(d):
    t, m, s = d
    return f'WithoutFaults<{t}>("{m}")' if s == 0 else f'FaultStatus<{t}>("{m}", {s})'
def cs(d):
    t, m, s = d
    return f'new("{t}", "{m}", {s})'

# declared: (status, how) how: "pp" = with application/problem+json (what ProducesProblem declares), "prt" = [ProducesResponseType] alone
def dattr(x):
    s, how = x
    return f'ProducesResponseType<ProblemDetails>({s}, "application/problem+json")' if how == "pp" else f'ProducesResponseType<ProblemDetails>({s})'

# name: (variants {suffix: class decls}, actions [(route, action decls, declared)])
CTLS = {
    "C04Ep": ({"": [], "S": [("HFault", "Down", 507)]},
              [("fx/ep/wo", [("HFault", "Down", 0)], []), ("fx/ep/keep", [], [])]),
    "C04CtWo": ({"": [("HFault", "Down", 0)]},
                [("fx/ct/wo/a", [], []), ("fx/ct/wo/b", [], [])]),
    "C04CtKeep": ({"": []}, [("fx/ct/keep", [], [])]),
    "C04Gr": ({"": []}, [("fx/gr/a", [], []), ("fx/gr/b", [], [])]),
    "C06K": ({"": []}, [("k", [], [])]),
    "C14Pp": ({"": []}, [("d/pp", [], [(404, "pp")])]),
    "C14Prt": ({"": []}, [("d/prt", [], [(404, "prt")])]),
    "C14None": ({"": []}, [("d/none", [], [])]),
    "C15M": ({"": []}, [("s/a", [], []), ("s/p", [("HFault", "Denied", 452)], [])]),
    "C15AS": ({"": []}, [("s/a", [("HFault", "Denied", 451)], []), ("s/k", [], [])]),
    "C15AW": ({"": []}, [("s/a", [("HFault", "Down", 0)], []), ("s/k", [], [])]),
    "C15CS": ({"": [("HFault", "Denied", 451)]}, [("s/a", [], []), ("s/p", [("HFault", "Denied", 452)], [])]),
    "C15CW": ({"": [("HFault", "Down", 0)]}, [("s/a", [], []), ("s/p", [("HFault", "Denied", 452)], [])]),
    "C15K": ({"": []}, [("s/k", [], [])]),
}

def pascal(route):
    return "".join(p[:1].upper() + p[1:] for p in route.replace("/", " ").split())

out = []
w = out.append
w("// Generated by faults-gen.py (the fault claims' MVC controllers, C04 C06 C14 C15): do not edit by hand.")
w("// Every action answers FxErr's errors; its route ends in the result type it answers (one, two, dup) or decl (one, with a")
w("// [ProducesResponseType<ProblemDetails>(429)] of its own). The table FxCtl.All restates what each class and action declares,")
w("// in ASP.NET's metadata order (controller, then action), as the input FaultClaim computes the expected response and document from.")
w("using CodoMetis.TypeKit;")
w("using CodoMetis.TypeKit.AspNetCore;")
w("using Microsoft.AspNetCore.Http;")
w("using Microsoft.AspNetCore.Http.HttpResults;")
w("using Microsoft.AspNetCore.Mvc;")
w("namespace Probes.Faults;")
w("")
for name, (variants, actions) in CTLS.items():
    w(f"internal abstract class Fx{name}Base : ControllerBase")
    w("{")
    for route, decls, declared in actions:
        for t in TS:
            attrs = [f'HttpGet("c/{route}/{t}")'] + [attr(d) for d in decls] + [dattr(x) for x in declared]
            if t == "decl": attrs.append("ProducesResponseType<ProblemDetails>(429)")
            w(f"    [{', '.join(attrs)}] public {RET[t]} {pascal(route)}{t.capitalize()}(int e) => {BODY[t]}.ToHttpResult();")
    w("}")
    for suffix, cdecls in variants.items():
        a = ", ".join(attr(d) for d in cdecls)
        w(f"[ApiController{', ' + a if a else ''}] internal sealed class Fx{name}{suffix}Api : Fx{name}Base {{ }}")
        w(f"{'[' + a + '] ' if a else ''}internal sealed class Fx{name}{suffix}Plain : Fx{name}Base {{ }}")
    w("")
w("public static partial class FxCtl")
w("{")
w("    static partial void Fill(Dictionary<string, Ctl> d)")
w("    {")
for name, (variants, actions) in CTLS.items():
    acts = ", ".join(f'new("{route}", [{", ".join(cs(x) for x in decls)}], [{", ".join(str(s) for s, _ in declared)}])' for route, decls, declared in actions)
    for suffix, cdecls in variants.items():
        w(f'        d["{name}{suffix}"] = new(typeof(Fx{name}{suffix}Api), typeof(Fx{name}{suffix}Plain), [{", ".join(cs(x) for x in cdecls)}], [{acts}]);')
w("    }")
w("}")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
