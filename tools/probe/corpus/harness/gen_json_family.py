#!/usr/bin/env python3
# Generates the JSON family's declarations from its rows (run from the repository root after `prober rows` changed a rows file):
#   harness/JsonFamilyShapes.g.cs  the source-generated contexts of C01, C10 and L06 (each lists exactly the shapes of its rows that run
#                                  under json.TypeInfoResolver=source-generated-context), and L06's polymorphic stand-ins over Option/Result
#   harness/L05Shapes.g.cs         L05's value objects and closed sets, one per (kind, wrapped, inheritance, site) its rows name
import json, os, re
C = 'tools/probe/corpus'

def rows(claim):
    p = f'{C}/rows/{claim}.json'
    return [r['row'] for r in json.load(open(p))['rows']] if os.path.exists(p) else []

WRAPPED = {'string': 'string', 'Guid': 'Guid', 'int': 'int', 'long': 'long', 'byte': 'byte', 'ulong': 'ulong', 'decimal': 'decimal',
           'double': 'double', 'bool': 'bool', 'char': 'char', 'DateTime': 'DateTime', 'DateTimeOffset': 'DateTimeOffset', 'DateOnly': 'DateOnly',
           'TimeOnly': 'TimeOnly', 'TimeSpan': 'TimeSpan', 'enum': 'PEnum', 'flags-enum': 'PFlags', 'Uri': 'Uri',
           'NodaTime.Instant': 'global::NodaTime.Instant', 'own-record-class': 'PRec'}
CLASSES = {'string', 'Uri', 'own-record-class'}
def san(s): return re.sub(r'[^A-Za-z0-9]', '_', s)
def vo(kind, wrapped): return 'PSet' if kind == 'closed-set' else f'V_{san(kind)}_{san(wrapped)}'
def vo_struct(kind): return kind in ('record-struct', 'validated-struct')
def plain(kind, wrapped): return 'string' if kind == 'closed-set' else WRAPPED[wrapped]
def plain_struct(kind, wrapped): return kind != 'closed-set' and wrapped not in CLASSES
def poly(kind, wrapped, is_vo):
    if is_vo: return 'PB_PSet' if kind == 'closed-set' else f'PB_{vo(kind, wrapped)}'
    return 'PBP_string_' if kind == 'closed-set' else f'PBP_{san(wrapped)}'

def holder(pos, con, m, struct, polybase):
    if pos == 'root': return m
    style = {'field': 'F', 'record-ctor-parameter': 'C', 'required-init': 'R'}.get(pos, 'P')
    mm = {'nullable-property': m + '?' if struct else m, 'list-element': f'List<{m}>', 'read-only-list-element': f'IReadOnlyList<{m}>',
          'array-element': f'{m}[]', 'immutable-array-element': f'ImmutableArray<{m}>', 'dictionary-key': f'Dictionary<{m}, int>',
          'dictionary-value': f'Dictionary<string, {m}>', 'in-patch': f'Patch<{m}>', 'polymorphic-derived-property': polybase}.get(pos, m)
    n = con.replace('-', '_')
    return f'Cn_{n}_{style}<{mm}, int>' if con == 'generic-type' else f'Cn_{n}_{style}<{mm}>'

def src_gen(r): return r.get('json.TypeInfoResolver') == 'source-generated-context'
def con_of(r): return 'class' if r['shape.position'] == 'root' else r['shape.containing']

OR_SHAPES = {'Option': ('O', 'Option<{v}>'), 'Result-T-E': ('RTE', 'Result<{v}, ShapeFault>'), 'Task-of-Result': ('RTE', 'Result<{v}, ShapeFault>'),
             'ValueTask-of-Result': ('RTE', 'Result<{v}, ShapeFault>'), 'Result-E': ('RE', 'Result<{v}>')}
def or_type(shape, v): return OR_SHAPES[shape][1].format(v=v)
def or_poly(shape, v): return f'L06PB_{san(v)}_{OR_SHAPES[shape][0]}'

contexts = {}
# C01: the decimal and the value object over one
types = set()
for r in rows('C01-decimal-spelling'):
    if not src_gen(r) or r['shape.kind'] == 'closed-set': continue
    k, p, c = r['shape.kind'], r['shape.position'], con_of(r)
    types.add(holder(p, c, 'decimal', True, 'PBP_decimal'))
    types.add(holder(p, c, vo(k, 'decimal'), vo_struct(k), poly(k, 'decimal', True)))
contexts['C01JsonContext'] = types
# C10: the wrapped type and the value object
types = set()
for r in rows('C10-preserve-guard'):
    if not src_gen(r): continue
    k, w, p, c = r['shape.kind'], r['shape.wrapped'], r['shape.position'], con_of(r)
    types.add(holder(p, c, plain(k, w), plain_struct(k, w), poly(k, w, False)))
    types.add(holder(p, c, vo(k, w), vo_struct(k), poly(k, w, True)))
contexts['C10JsonContext'] = types
# L06: the value object (whose document is the read's input) and the Option or Result over it
types = set()
for r in rows('L06-off-the-wire'):
    if not src_gen(r): continue
    k, w, p, c, s = r['shape.kind'], r['shape.wrapped'], r['shape.position'], con_of(r), r['or.shape']
    v = vo(k, w)
    types.add(holder(p, c, v, vo_struct(k), poly(k, w, True)))
    types.add(holder(p, c, or_type(s, v), True, or_poly(s, v)))
    types.add(plain(k, w))   # the wrapped type, as an application lists it (Generators README#json: a context sees no further than a converter)
contexts['L06JsonContext'] = types

out = ['// <auto-generated/> by harness/gen_json_family.py from the rows of C01, C10 and L06. Do not edit.',
       '#nullable disable', '#pragma warning disable CS8618, CS1591, CMTK0005, CMTK0006',
       'using System.Collections.Immutable;', 'using System.Text.Json.Serialization;', 'using CodoMetis.TypeKit;', 'using Probes.Shapes;',
       'namespace Probes.Json;', '']
# L06's polymorphic stand-ins: a base per value object and shape, its derived type holding the Option or Result
vos = [vo(k, w) for k in ('record-struct', 'sealed-record-class', 'validated-struct', 'validated-class') for w in WRAPPED] + ['PSet']
for v in vos:
    for key, pattern in {'O': 'Option<{v}>', 'RTE': 'Result<{v}, ShapeFault>', 'RE': 'Result<{v}>'}.items():
        b = f'L06PB_{san(v)}_{key}'; d = f'L06PD_{san(v)}_{key}'
        out.append(f'[JsonPolymorphic] [JsonDerivedType(typeof({d}), "d")] public abstract class {b} {{ }}')
        out.append(f'public sealed class {d} : {b} {{ public {pattern.format(v=v)} Value {{ get; set; }} }}')
out.append('')
for name, ts in contexts.items():
    for i, t in enumerate(sorted(ts)):
        # a generic or array shape gets a name of its own (two would collide); a plain type keeps the serializer's (its built-in converter)
        out.append(f'[JsonSerializable(typeof({t}), TypeInfoPropertyName = "T{i}")]' if '<' in t or '[' in t else f'[JsonSerializable(typeof({t}))]')
    out.append(f'public partial class {name} : JsonSerializerContext {{ }}')
    out.append('')
open(f'{C}/harness/JsonFamilyShapes.g.cs', 'w').write('\n'.join(out))

# L05: one type per (kind, wrapped, inheritance, site); bases shared by inheritance
SAMPLES = {  # C# expressions: a1, a2 (equal to a1 by the wrapped type's own equality, in another form), b (unequal, greater where ordered)
    'string': ('"alpha"', 'new string("alpha".ToCharArray())', '"beta"'),
    'Guid': ('Guid.Parse("11111111-1111-1111-1111-111111111111")', 'new Guid("11111111111111111111111111111111")', 'Guid.Parse("22222222-2222-2222-2222-222222222222")'),
    'int': ('42', '42', '43'), 'long': ('4200000000L', '4200000000L', '4200000001L'), 'byte': ('(byte)7', '(byte)7', '(byte)8'),
    'ulong': ('4200000000UL', '4200000000UL', '4200000001UL'), 'decimal': ('7.8m', '7.80m', '7.81m'), 'double': ('0.0', '-0.0', '1.5'),
    'bool': ('false', 'false', 'true'), 'char': ("'a'", "'a'", "'b'"),
    'DateTime': ('new DateTime(2026, 10, 15, 8, 30, 0, DateTimeKind.Utc)', 'new DateTime(2026, 10, 15, 8, 30, 0, DateTimeKind.Unspecified)', 'new DateTime(2026, 10, 15, 8, 31, 0, DateTimeKind.Utc)'),
    'DateTimeOffset': ('new DateTimeOffset(2026, 10, 15, 8, 30, 0, TimeSpan.Zero)', 'new DateTimeOffset(2026, 10, 15, 10, 30, 0, TimeSpan.FromHours(2))', 'new DateTimeOffset(2026, 10, 15, 8, 31, 0, TimeSpan.Zero)'),
    'DateOnly': ('new DateOnly(2026, 10, 15)', 'DateOnly.FromDayNumber(new DateOnly(2026, 10, 15).DayNumber)', 'new DateOnly(2026, 10, 16)'),
    'TimeOnly': ('new TimeOnly(8, 30, 15)', 'new TimeOnly(new TimeOnly(8, 30, 15).Ticks)', 'new TimeOnly(8, 30, 16)'),
    'TimeSpan': ('TimeSpan.FromMinutes(90)', 'TimeSpan.FromSeconds(5400)', 'TimeSpan.FromMinutes(91)'),
    'enum': ('PEnum.B', '(PEnum)1', 'PEnum.C'), 'flags-enum': ('PFlags.P | PFlags.Q', '(PFlags)3', 'PFlags.R'),
    'Uri': ('new Uri("https://example.com/a")', 'new Uri("HTTPS://EXAMPLE.COM/a")', 'new Uri("https://example.com/b")'),
    'NodaTime.Instant': ('global::NodaTime.Instant.FromUtc(2026, 10, 15, 8, 30)', 'global::NodaTime.Instant.FromUnixTimeTicks(global::NodaTime.Instant.FromUtc(2026, 10, 15, 8, 30).ToUnixTimeTicks())', 'global::NodaTime.Instant.FromUtc(2026, 10, 15, 8, 31)'),
    'own-record-class': ('new PRec { A = "x", B = 1 }', 'new PRec { A = new string("x".ToCharArray()), B = 1 }', 'new PRec { A = "y", B = 1 }'),
}
BASES = {'base-depth-1': 'L05B1', 'base-depth-2': 'L05B2b', 'base-depth-3': 'L05B3c', 'base-explicit-IEquatable': 'L05E1'}
CBASES = {'base-depth-1': 'L05CB1', 'base-depth-2': 'L05CB2b', 'base-depth-3': 'L05CB3c', 'base-explicit-IEquatable': 'L05CE1'}
# a row the covering array made with an excluded pair runs the nearest shape that exists (the probe notes the substitution)
def l05_site(r): return 'top-level' if r['shape.site'] == 'in-generic-type' else r['shape.site']
def l05_inh(r): return 'none' if vo_struct(r['shape.kind']) and r['shape.inheritance'].startswith('base-') else r['shape.inheritance']
tuples = sorted({(r['shape.kind'], '-' if r['shape.kind'] == 'closed-set' else r['shape.wrapped'], l05_inh(r), l05_site(r)) for r in rows('L05-equality')})
o = ['// <auto-generated/> by harness/gen_json_family.py from the rows of L05-equality. Do not edit.',
     '#nullable enable',
     '#pragma warning disable CS1591, CMTK0005, CMTK1023 // CMTK1023: a base record with an explicit IEquatable is the shape under test',
     'using CodoMetis.TypeKit;', 'using CodoMetis.TypeKit.ValueObjects;', 'using CodoMetis.TypeKit.ClosedSets;', 'using Probes.Shapes;',
     'namespace Probes.Json;', '',
     'public interface IL05Tag { string Tag { get; } }',
     'public abstract record L05B1;', 'public abstract record L05B2a;', 'public abstract record L05B2b : L05B2a;',
     'public abstract record L05B3a;', 'public abstract record L05B3b : L05B3a;', 'public abstract record L05B3c : L05B3b;',
     '// a deeper base whose own IEquatable says "never equal": the value object must not use it',
     'public abstract record L05E0 : IEquatable<L05E0> { bool IEquatable<L05E0>.Equals(L05E0? other) => false; }',
     'public abstract record L05E1 : L05E0;',
     'public abstract class L05CB1;', 'public abstract class L05CB2a;', 'public abstract class L05CB2b : L05CB2a;',
     'public abstract class L05CB3a;', 'public abstract class L05CB3b : L05CB3a;', 'public abstract class L05CB3c : L05CB3b;',
     'public abstract class L05CE0 : IEquatable<L05CE0> { bool IEquatable<L05CE0>.Equals(L05CE0? other) => ReferenceEquals(this, other); }',
     'public abstract class L05CE1 : L05CE0;', '']
reg = []
for i, (k, w, inh, site) in enumerate(tuples):
    n = f'L05_{i}_{san(k)}_{san(w)}'
    bases = []
    if inh.startswith('base-'): bases.append((CBASES if k == 'closed-set' else BASES)[inh])
    tag = ' string IL05Tag.Tag => "t";' if inh == 'explicit-interface-member' else ''
    if inh == 'explicit-interface-member': bases.append('IL05Tag')
    head = ', '.join(bases + [''])
    if k == 'closed-set':
        decl = f'public sealed partial class {n} : {head}IClosedSet<{n}> {{ public static readonly {n} Alpha = new(); public static readonly {n} Beta = new();{tag} }}'
    else:
        t = WRAPPED[w]
        if k == 'record-struct': decl = f'public readonly partial record struct {n} : {head}IValue<{t}> {{{tag} }}'
        elif k == 'sealed-record-class': decl = f'public sealed partial record {n} : {head}IValue<{t}> {{{tag} }}'
        elif k == 'validated-struct': decl = f'public readonly partial record struct {n} : {head}IValidatedValue<{n}, {t}, ShapeFault> {{ public static Result<{n}, ShapeFault> Create({t} value) => new {n}(value);{tag} }}'
        else: decl = f'public sealed partial record {n} : {head}IValidatedValue<{n}, {t}, ShapeFault> {{ public static Result<{n}, ShapeFault> Create({t} value) => new {n}(value);{tag} }}'
    if site == 'top-level': o.append(decl); full = n
    elif site == 'nested-in-class': o.append(f'public partial class L05Oc{i} {{ {decl} }}'); full = f'L05Oc{i}.{n}'
    elif site == 'nested-in-struct': o.append(f'public partial struct L05Os{i} {{ {decl} }}'); full = f'L05Os{i}.{n}'
    else: o.append(f'public partial class L05Ot{i} {{ public partial class Inner {{ {decl} }} }}'); full = f'L05Ot{i}.Inner.{n}'
    if k == 'closed-set': reg.append(f'        Add("{k}", "-", "{inh}", "{site}", typeof({full}), () => {full}.Alpha, () => {full}.All.First(m => m.Name == "Alpha"), () => {full}.Beta);')
    else:
        a1, a2, b = SAMPLES[w]
        reg.append(f'        Add("{k}", "{w}", "{inh}", "{site}", typeof({full}), () => {a1}, () => {a2}, () => {b});')
o += ['', 'public static partial class L05Registry', '{', '    static partial void Fill()', '    {'] + reg + ['    }', '}', '']
open(f'{C}/harness/L05Shapes.g.cs', 'w').write('\n'.join(o))
print({k: len(v) for k, v in contexts.items()}, 'L05 types', len(tuples))
