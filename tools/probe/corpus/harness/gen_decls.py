# Generates the declarations the C09 and C11 probes run against, one value object per row, from the rows files:
#   tools/probe/corpus/harness/C09Shapes.g.cs, tools/probe/corpus/harness/C11Shapes.g.cs
# Each row's excluded values are replaced by the nearest that exists; the table names the effective settings and the row's
# own key, which the probe checks against the rows file it runs (a stale file is a harness error).
import json, sys, os
WT = sys.argv[1]
C = WT + '/tools/probe/corpus'

def rows(claim):
    p = f'{C}/rows/{claim}.json'
    return [r['row'] for r in json.load(open(p))['rows']]

def key(row):
    return ';'.join(f'{k}={row[k]}' for k in sorted(row))

W = {
    'string': 'string', 'Guid': 'global::System.Guid', 'int': 'int', 'long': 'long', 'byte': 'byte', 'ulong': 'ulong', 'decimal': 'decimal',
    'double': 'double', 'bool': 'bool', 'char': 'char', 'DateTime': 'global::System.DateTime', 'DateTimeOffset': 'global::System.DateTimeOffset',
    'DateOnly': 'global::System.DateOnly', 'TimeOnly': 'global::System.TimeOnly', 'TimeSpan': 'global::System.TimeSpan',
    'enum': 'global::Probes.Shapes.PEnum', 'flags-enum': 'global::Probes.Shapes.PFlags', 'Uri': 'global::System.Uri',
    'NodaTime.Instant': 'global::NodaTime.Instant', 'own-record-class': 'global::Probes.Shapes.PRec',
}

def at_site(site, p, idx, inner):
    o, q = f'{p}O{idx}', f'{p}P{idx}'
    if site == 'top-level': return inner, ''
    if site == 'nested-in-class': return f'public static partial class {o}\n{{\n{inner}}}\n', f'{o}.'
    if site == 'nested-in-struct': return f'public partial struct {o}\n{{\n{inner}}}\n', f'{o}.'
    if site == 'nested-two-levels': return f'public static partial class {o}\n{{\npublic sealed partial class {q}\n{{\n{inner}}}\n}}\n', f'{o}.{q}.'
    raise ValueError(site)

def depth(inh):
    return {'base-depth-2': 2, 'base-depth-3': 3}.get(inh, 1 if inh in ('base-depth-1', 'base-explicit-IEquatable', 'explicit-interface-member') else 0)

HEAD = '''// <auto-generated/> by gen_decls.py from rows/{claim}.json: one value object per row. Do not edit; regenerate with the rows.
#nullable enable
// CMTK1023: the bases' own equality is the point (C09) or beside it (C11); CS8851: a base's Equals without GetHashCode, on purpose.
#pragma warning disable CMTK1023, CS8851, CS1591
using CodoMetis.TypeKit;
using CodoMetis.TypeKit.ValueObjects;
namespace Probes.Build.{ns};
'''

def gen_c09():
    claim = 'C09-base-record-equality'
    out = [HEAD.format(claim=claim, ns='C09')]
    table = []
    for idx, row in enumerate(rows(claim)):
        subs = []
        kind = row['shape.kind']
        if kind in ('record-struct', 'closed-set'): subs.append(('shape.kind', 'sealed-record-class')); kind = 'sealed-record-class'
        elif kind == 'validated-struct': subs.append(('shape.kind', 'validated-class')); kind = 'validated-class'
        site = row['shape.site']
        if site == 'in-generic-type': subs.append(('shape.site', 'nested-in-class')); site = 'nested-in-class'
        inh = row['shape.inheritance']
        if inh == 'none': subs.append(('shape.inheritance', 'base-depth-1')); inh = 'base-depth-1'
        eq = row['base-equality']; w = W[row['shape.wrapped']]
        n = depth(inh); body = []
        if inh == 'explicit-interface-member': body.append(f'public interface IMark{idx} {{ int Mark(); }}')
        for d in range(n, 0, -1):
            name = f'B{idx}_{d}'; parents = [] if d == n else [f'B{idx}_{d+1}']; members = []
            if d == n:
                if eq == 'override-Equals': members.append(f'public virtual bool Equals({name}? other) => ReferenceEquals(this, other);')
                elif eq == 'override-GetHashCode': members.append('public override int GetHashCode() => System.Runtime.CompilerServices.RuntimeHelpers.GetHashCode(this);')
                elif eq == 'explicit-IEquatable':
                    parents.append(f'System.IEquatable<{name}>'); members.append(f'bool System.IEquatable<{name}>.Equals({name}? other) => ReferenceEquals(this, other);')
            if d == 1 and inh == 'base-explicit-IEquatable' and not (eq == 'explicit-IEquatable' and n == 1):
                parents.append(f'System.IEquatable<{name}>'); members.append(f'bool System.IEquatable<{name}>.Equals({name}? other) => ReferenceEquals(this, other);')
            if d == 1 and inh == 'explicit-interface-member':
                parents.append(f'IMark{idx}'); members.append(f'int IMark{idx}.Mark() => 1;')
            body.append(f'public abstract record {name}' + (' : ' + ', '.join(parents) if parents else '') + ' { ' + ' '.join(members) + ' }')
        v = f'V{idx}'
        if kind == 'validated-class':
            body.append(f'public sealed partial record {v} : B{idx}_1, IValidatedValue<{v}, {w}, global::Probes.Shapes.ShapeFault>\n{{\n    public static Result<{v}, global::Probes.Shapes.ShapeFault> Create({w} value) => new {v}(value);\n}}')
            make = f'x => {{0}}{v}.FromKnownGood(({w})x)'
        else:
            body.append(f'public sealed partial record {v} : B{idx}_1, IValue<{w}>;')
            make = f'x => {{0}}{v}.From(({w})x)'
        text, q = at_site(site, '', idx, '\n'.join(body) + '\n')
        out.append(f'// row {idx}\n' + text)
        bases = ', '.join(f'typeof({q}B{idx}_{d})' for d in range(1, n + 1))
        subs_cs = ', '.join(f'("{a}", "{b}")' for a, b in subs)
        table.append(f'        new({idx}, "{key(row)}", "{kind}", "{site}", "{inh}", typeof({q}{v}), [{bases}], {make.format(q)}, [{subs_cs}]),')
    out.append('public static partial class C09Table\n{\n    public static readonly C09Case[] Cases =\n    [\n' + '\n'.join(table) + '\n    ];\n}\n')
    open(f'{C}/harness/C09Shapes.g.cs', 'w').write('\n'.join(out))
    print('C09', len(table))

CONTROL = {'implicit-result': 'global::Probes.Build.C11ParsedShape', 'ref-text': 'global::Probes.Build.C11ParsesFromIn', 'abstract-string-ctor': 'global::Probes.Build.C11ConstructedConcrete'}
ODD = {'implicit-result': 'global::Probes.Build.C11ParsesToInt', 'ref-text': None, 'abstract-string-ctor': 'global::Probes.Build.C11AbstractText'}

def gen_c11():
    claim = 'C11-parse-shapes-build'
    out = [HEAD.format(claim=claim, ns='C11')]
    table = []
    for idx, row in enumerate(rows(claim)):
        subs = []
        kind = row['shape.kind']
        if kind == 'closed-set': subs.append(('shape.kind', 'sealed-record-class')); kind = 'sealed-record-class'
        site = row['shape.site']
        if site == 'in-generic-type': subs.append(('shape.site', 'nested-in-class')); site = 'nested-in-class'
        inh = row['shape.inheritance']
        struct = kind in ('record-struct', 'validated-struct')
        if struct and inh not in ('none', 'explicit-interface-member'): subs.append(('shape.inheritance', 'none')); inh = 'none'
        shape = row['parse-shape']
        if shape == 'ordinary': w = W[row['shape.wrapped']]
        elif shape == 'ref-text': w = 'global::Probes.Build.C11ParsesByRef' if idx % 2 == 0 else 'global::Probes.Build.C11ConstructedByRef'
        else: w = ODD[shape]
        n = depth(inh) if not struct else 0
        if inh == 'explicit-interface-member': n = 0
        body = []
        if inh == 'explicit-interface-member': body.append(f'public interface IMark{idx} {{ int Mark(); }}')
        def declare(v, b, w):
            mark = f', IMark{idx}' if inh == 'explicit-interface-member' else ''
            for d in range(n, 0, -1):
                name = f'{b}{idx}_{d}'; parents = [] if d == n else [f'{b}{idx}_{d+1}']; members = []
                if d == 1 and inh == 'base-explicit-IEquatable':
                    parents.append(f'System.IEquatable<{name}>'); members.append(f'bool System.IEquatable<{name}>.Equals({name}? other) => ReferenceEquals(this, other);')
                body.append(f'public abstract record {name}' + (' : ' + ', '.join(parents) if parents else '') + ' { ' + ' '.join(members) + ' }')
            base = f'{b}{idx}_1, ' if n > 0 else ''
            m = f' int IMark{idx}.Mark() => 1;' if mark else ''
            fault = 'global::Probes.Shapes.ShapeFault'
            if kind == 'record-struct': body.append(f'public readonly partial record struct {v} : IValue<{w}>{mark} {{{m} }}')
            elif kind == 'sealed-record-class': body.append(f'public sealed partial record {v} : {base}IValue<{w}>{mark} {{{m} }}')
            elif kind == 'validated-struct': body.append(f'public readonly partial record struct {v} : IValidatedValue<{v}, {w}, {fault}>{mark}\n{{\n    public static Result<{v}, {fault}> Create({w} value) => new {v}(value);{m}\n}}')
            elif kind == 'validated-class': body.append(f'public sealed partial record {v} : {base}IValidatedValue<{v}, {w}, {fault}>{mark}\n{{\n    public static Result<{v}, {fault}> Create({w} value) => new {v}(value);{m}\n}}')
        v = f'V{idx}'
        declare(v, 'B', w)
        control = CONTROL.get(shape)
        if control: declare(f'VC{idx}', 'BC', control)
        text, q = at_site(site, '', idx, '\n'.join(body) + '\n')
        out.append(f'// row {idx}\n' + text)
        subs_cs = ', '.join(f'("{a}", "{b}")' for a, b in subs)
        ctl = f'typeof({q}VC{idx}), typeof({control})' if control else 'null, null'
        table.append(f'        new({idx}, "{key(row)}", "{kind}", "{site}", "{inh}", typeof({q}{v}), typeof({w}), {ctl}, [{subs_cs}]),')
    out.append('public static partial class C11Table\n{\n    public static readonly C11Case[] Cases =\n    [\n' + '\n'.join(table) + '\n    ];\n}\n')
    open(f'{C}/harness/C11Shapes.g.cs', 'w').write('\n'.join(out))
    print('C11', len(table))

which = sys.argv[2:] or ['C09', 'C11']
if 'C09' in which and os.path.exists(f'{C}/rows/C09-base-record-equality.json'): gen_c09()
if 'C11' in which and os.path.exists(f'{C}/rows/C11-parse-shapes-build.json'): gen_c11()
