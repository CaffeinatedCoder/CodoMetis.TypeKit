// Claim E14-inheritance-key-generation (README#keys): "The root of an inheritance hierarchy follows the same rules under TPH and TPT. Under TPC, as for an int key, the key is generated only where the provider numbers the whole hierarchy from a sequence (PostgreSQL, SQL Server) ... SQLite has no such sequence, so there you assign it." Key over Guid: yours to assign.
// Oracle: differential against the same hierarchy keyed by the wrapped type (default keys on two leaf types, SaveChanges, the keys read back; an int/long key over TPH/TPT must be generated, distinct and non-zero),
// plus the claim for assigned keys: every hierarchy round-trips assigned keys polymorphically, and a Guid key is never generated by default.
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Probes.Ef;
using Probes.Shapes;
namespace Probes;
public sealed class E14InheritanceKeyProbe
{
    public static TheoryData<string, int> Data() => Rows.Data("E14InheritanceKeyProbe");
    [Theory, MemberData(nameof(Data))]
    public Task Row(string probe, int idx) => Rec.Run(probe, idx, Check);

    static Action<Microsoft.EntityFrameworkCore.ModelBuilder> Cfg(string strategy, Type root, Type a, Type b) => mb =>
    {
        var rb = mb.Entity(root); rb.HasKey("Id");
        var ab = mb.Entity(a); var bb = mb.Entity(b);
        switch (strategy)
        {
            case "TPH": rb.ToTable("root"); break;
            case "TPT": rb.UseTptMappingStrategy(); rb.ToTable("root"); ab.ToTable("leafa"); bb.ToTable("leafb"); break;
            case "TPC": rb.UseTpcMappingStrategy(); ab.ToTable("leafa"); bb.ToTable("leafb"); break;
        }
    };

    static async Task<string?> Check(Probes.Shapes.Row r)
    {
        var w = r["shape.wrapped"]; var strategy = r["ef.inheritance"];
        var kind = EfX.Kinds[r.Index % EfX.Kinds.Length];
        var e = KeyRegistry.All.First(x => x.Kind == kind && x.Wrapped == w);

        // phase A: default keys on one leaf of each type
        async Task<string> Default(bool vo)
        {
            var kt = vo ? e.Vo : e.Plain;
            Type root = typeof(RootE<>).MakeGenericType(kt), a = typeof(LeafA<>).MakeGenericType(kt), b = typeof(LeafB<>).MakeGenericType(kt);
            await using var db = new EfDb(Cfg(strategy, root, a, b), typeKit: vo);
            try
            {
                await db.Context.Database.EnsureCreatedAsync();
                var gen = db.Context.Model.FindEntityType(root)!.FindProperty("Id")!.ValueGenerated;
                var items = new[] { EfX.New(a), EfX.New(b), EfX.New(a) };
                foreach (var x in items) db.Context.Add(x);
                await db.Context.SaveChangesAsync();
                return $"gen={gen} keys=[" + string.Join(",", items.Select(x => EfX.Plainify(EfX.Get(x, "Id")))) + "]";
            }
            catch (Exception ex) { return "threw:" + ex.GetType().Name; }
        }
        // phase B: assigned keys, polymorphic read back
        async Task<string> Assigned(bool vo)
        {
            var kt = vo ? e.Vo : e.Plain;
            Type root = typeof(RootE<>).MakeGenericType(kt), a = typeof(LeafA<>).MakeGenericType(kt), b = typeof(LeafB<>).MakeGenericType(kt);
            await using var db = new EfDb(Cfg(strategy, root, a, b), typeKit: vo);
            await db.Context.Database.EnsureCreatedAsync();
            object K(int i) { var p = EfX.Sample(w, i); return vo ? e.MakeVo(p) : p; }
            var items = new[] { (a, 0, "a0"), (b, 1, "b1"), (a, 2, "a2") };
            foreach (var (t, i, name) in items) { var x = EfX.New(t); EfX.Set(x, "Id", K(i)); EfX.Set(x, "Name", name); db.Context.Add(x); }
            await db.Context.SaveChangesAsync();
            db.Context.ChangeTracker.Clear();
            var all = EfX.Enumerate(Q.SetOf(db.Context, root)).Select(x => $"{x.GetType().Name.Split('`')[0]}:{EfX.Get(x, "Name")}:{EfX.Plainify(EfX.Get(x, "Id"))}").OrderBy(s => s, StringComparer.Ordinal);
            db.Context.ChangeTracker.Clear();
            var found = await db.Context.FindAsync(root, K(1));
            return string.Join(",", all) + " find1=" + (found is null ? "null" : (string)EfX.Get(found, "Name")!);
        }

        var vA = await Default(true);
        var vB = await Assigned(true);
        var pB = await Assigned(false);
        if (vB != pB) return $"assigned keys differ from the plain hierarchy: VO {vB} | plain {pB}";
        if (!vB.Contains("find1=b1")) return "Find by the assigned key failed: " + vB;

        if (w == "Guid")
        {
            // documented: yours to assign, never generated by default (EF generates a plain Guid key; TypeKit's is Never): not-promised guid-key-not-generated
            if (!vA.StartsWith("gen=Never") && !vA.StartsWith("threw")) return "Guid key under " + strategy + " is not 'yours to assign': " + vA;
            return null;
        }
        var pA = await Default(false);
        if (vA != pA) return $"default keys differ from the plain hierarchy under {strategy}: VO {vA} | plain {pA}";
        if (strategy is "TPH" or "TPT")
        {
            // documented: the root of a TPH or TPT hierarchy is generated
            var keys = vA.Substring(vA.IndexOf('[') + 1).TrimEnd(']').Split(',');
            if (!vA.StartsWith("gen=OnAdd") || keys.Distinct().Count() != 3 || keys.Any(k => k is "0" or "")) return $"{strategy} root key is not generated on add: {vA}";
        }
        else r.Note(NoteKeys.TpcSqliteNoSequenceAssignChecked);
        return null;
    }
}
