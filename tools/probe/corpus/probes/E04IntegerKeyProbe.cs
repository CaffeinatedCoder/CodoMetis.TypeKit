// Claim E04-integer-key-generated (README#keys): "A single-column key over an integer is generated on add, like a key of that integer type ... not byte. A key over char is yours to assign: never generated. A key over a Guid is yours to assign ... To have EF generate it instead, configure ValueGeneratedOnAdd()."
// Oracle: differential against the same key declared with the wrapped type (two entities added with default keys, SaveChanges, the keys read back), except the documented char and Guid keys, which must not be generated by default.
using Microsoft.EntityFrameworkCore;
using Probes.Ef;
using Probes.Shapes;
namespace Probes;
public sealed class E04IntegerKeyProbe
{
    public static TheoryData<string, int> Data() => Rows.Data("E04-integer-key-generated");
    [Theory, MemberData(nameof(Data))]
    public Task Row(string claim, int idx) => Rec.Run(claim, idx, Check);

    static async Task<string?> Check(Probes.Shapes.Row r)
    {
        var e = KeyRegistry.Of(r);
        var config = r["ef.key-config"];
        async Task<string> Side(Type keyType, bool vo)
        {
            var entity = typeof(EntK<>).MakeGenericType(keyType);
            Action<ModelBuilder> cfg = mb =>
            {
                var eb = mb.Entity(entity); eb.ToTable("t"); eb.HasKey("Id");
                var pb = eb.Property("Id");
                if (config == "ValueGeneratedOnAdd") pb.ValueGeneratedOnAdd();
                if (config == "ValueGeneratedNever") pb.ValueGeneratedNever();
            };
            await using var db = new EfDb(cfg, typeKit: vo);
            try
            {
                await db.Context.Database.EnsureCreatedAsync();
                var rows = new[] { Activator.CreateInstance(entity)!, Activator.CreateInstance(entity)! };
                foreach (var row in rows) db.Context.Add(row);
                await db.Context.SaveChangesAsync();
                return "keys=[" + string.Join(",", rows.Select(x => Norm(entity.GetProperty("Id")!.GetValue(x)))) + "]";
            }
            catch (Exception) { return "threw"; }   // where it throws (creating the table, or the insert) differs by provider rule; that it cannot generate is the outcome
        }
        string Norm(object? k)
        {
            if (k is not null && k.GetType().Namespace == "Probes.Ef") k = k.GetType().GetProperty("Value")!.GetValue(k);
            return k switch { null => "null", Guid g => g == Guid.Empty ? "empty" : "guid", string str when Guid.TryParse(str, out _) => "guid", _ => Convert.ToString(k, System.Globalization.CultureInfo.InvariantCulture)! };
        }
        var voOut = await Side(e.Vo, true);
        var plainOut = await Side(e.Plain, false);
        if (config == "default" && e.Wrapped is "char" or "Guid" && config == "default")
        {
            // documented: yours to assign, never generated; the second default key collides, or both stay default
            r.Note(NoteKeys.DocumentedCharGuidNotGeneratedChecked);
            return voOut.StartsWith("threw") || voOut is "keys=[empty,empty]" or "keys=[\0,\0]" ? null : $"{e.Wrapped} key was generated by default: {voOut} (plain: {plainOut})";
        }
        return voOut == plainOut ? null : $"VO key: {voOut}; plain key: {plainOut}";
    }
}
