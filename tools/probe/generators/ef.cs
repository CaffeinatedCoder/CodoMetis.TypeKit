// Writes the EF probes' shapes, one mode per file of tools/probe/corpus/harness:
//
//   catalogue  EfShapes.g.cs   one value object per (shape.kind, shape.wrapped, shape.site) the rows name, and EfRegistry
//   keys       KeyShapes.g.cs  the same for the key claims (a row without shape.site is top-level), and KeyRegistry
//   top-level  EfShapes3.g.cs  every kind at top level for each wrapped type the catalogue holds, and Reg3
//   nested     EfShapes4.g.cs  every kind at each nested site for each wrapped type the catalogue holds, and Reg4
//
//   dotnet run tools/probe/generators/ef.cs -- catalogue --out tools/probe/corpus/harness/EfShapes.g.cs \
//       --rows tools/probe/corpus/rows/E01ColumnParityProbe.json.gz --first 90 \
//       --rows tools/probe/corpus/rows/E02ValueTranslatesProbe.json.gz --first 108
//
// --rows names a rows file (gzipped JSON, written by `prober rows`); --first after it reads only its first n rows.
// The catalogue is E01's and E02's first round of rows: the rows appended since run on the complete grids of
// top-level and nested, which take the same rows to learn which wrapped types the catalogue holds, in its order,
// and which of them it validates. GeneratedHarnessTests in the conventions tests holds each file to this output,
// with the arguments it lists.
using System.IO.Compression;
using System.Text;
using System.Text.Json.Nodes;

try
{
    var mode = args.Length > 0 ? args[0] : throw new GeneratorError("a mode is required: catalogue, keys, top-level or nested");
    var combos = Combos(RowsArguments(args));
    var text = mode switch
    {
        "catalogue" => Catalogue(combos, keys: false),
        "keys" => Catalogue(combos, keys: true),
        "top-level" => TopLevel(combos),
        "nested" => Nested(combos),
        _ => throw new GeneratorError($"unknown mode {mode}"),
    };
    File.WriteAllText(Arg(args, "--out"), text, new UTF8Encoding(false));
    return 0;
}
catch (GeneratorError e)
{
    Console.Error.WriteLine($"ef.cs: {e.Message}");
    return 2;
}

// The distinct (kind, wrapped, site) of the rows, sorted ordinally. A closed set and a value object nested in a
// generic type (CMTK1005 at build) have no shape here.
static List<(string Kind, string Wrapped, string Site)> Combos(IEnumerable<Dictionary<string, string>> rows) =>
[
    .. rows.Where(r => r["shape.kind"] != "closed-set")
           .Select(r => (Kind: r["shape.kind"], Wrapped: r["shape.wrapped"], Site: r.GetValueOrDefault("shape.site", "top-level")))
           .Where(c => c.Site != "in-generic-type")
           .Distinct()
           .OrderBy(c => c.Kind, StringComparer.Ordinal).ThenBy(c => c.Wrapped, StringComparer.Ordinal).ThenBy(c => c.Site, StringComparer.Ordinal),
];

static string Catalogue(List<(string Kind, string Wrapped, string Site)> combos, bool keys)
{
    var o = new List<string>
    {
        keys
            ? "// <auto-generated/> by tools/probe/generators/ef.cs keys; the EF key probes' shape catalogue (shape.kind x shape.wrapped). Do not edit."
            : "// <auto-generated/> by tools/probe/generators/ef.cs catalogue; the EF probes' shape catalogue (shape.kind x shape.wrapped x shape.site). Do not edit.",
        "#nullable enable", Grids.Pragmas,
        "using CodoMetis.TypeKit;", "using CodoMetis.TypeKit.ValueObjects;", "using Probes.Shapes;", "namespace Probes.Ef;",
    };
    var prefix = keys ? "K" : "";
    var registry = new List<string>();
    foreach (var (kind, key, site) in combos)
    {
        var w = Wrapped.Of(key);
        var n = $"{(keys ? "K" : "E")}_{Ident(kind)}_{Ident(key)}";
        string path;
        switch (site)
        {
            case "top-level":
                o.Add(Declaration(kind, n, w));
                path = n;
                break;
            case "nested-in-class":
                o.Add($"public static class C{prefix}_{n}\n{{\n{Declaration(kind, "V", w)}\n}}");
                path = $"C{prefix}_{n}.V";
                break;
            case "nested-in-struct":
                o.Add($"public struct S{prefix}_{n}\n{{\n{Declaration(kind, "V", w)}\n}}");
                path = $"S{prefix}_{n}.V";
                break;
            case "nested-two-levels":
                o.Add($"public static class C2{prefix}_{n}\n{{\n public static class Inner\n {{\n{Declaration(kind, "V", w)}\n }}\n}}");
                path = $"C2{prefix}_{n}.Inner.V";
                break;
            default:
                throw new GeneratorError($"shape.site {site} has no shape here");
        }
        registry.Add($"        e.Add(new EfEntry(\"{kind}\", \"{key}\", \"{site}\", typeof({path}), typeof({w.Type}), () => {w.Valid}));");
    }
    o.Add(keys
        ? "public static partial class KeyRegistry\n{\n" +
          "    public static readonly List<EfEntry> All = Build();\n" +
          "    static List<EfEntry> Build() { var e = new List<EfEntry>(); Fill(e); return e; }\n" +
          "    public static EfEntry Of(Probes.Shapes.Row r) { var k = r[\"shape.kind\"]; var w = r[\"shape.wrapped\"]; return All.First(x => x.Kind == k && x.Wrapped == w); }\n" +
          "    public static void Fill(List<EfEntry> e)\n    {"
        : "public static partial class EfRegistry\n{\n    static partial void Fill(List<EfEntry> e)\n    {");
    o.AddRange(registry);
    o.Add("    }\n}");
    return string.Join("\n", o) + "\n";
}

static string Declaration(string kind, string name, Wrapped w) => kind switch
{
    "record-struct" => $"public readonly partial record struct {name} : IValue<{w.Type}>;",
    "sealed-record-class" => $"public sealed partial record class {name} : IValue<{w.Type}>;",
    "validated-struct" or "validated-class" =>
        $"public {(kind == "validated-struct" ? "readonly partial record struct" : "sealed partial record class")} {name} : IValidatedValue<{name}, {w.Type}, ShapeFault>\n{{\n" +
        $"    public static Result<{name}, ShapeFault> Create({w.Type} value) =>\n" +
        $"        EqualityComparer<{w.Type}>.Default.Equals(value, {w.Refused}) ? Result.Error(ShapeFault.Refused) : new {name}(value);\n}}",
    _ => throw new GeneratorError($"shape.kind {kind} has no declaration here"),
};

// The grids: the catalogue's wrapped types in its order; the validated kinds only for a wrapped type the catalogue validates.
static (List<string> Wrapped, HashSet<string> Validated) Grid(List<(string Kind, string Wrapped, string Site)> combos) =>
(
    [.. combos.Select(c => c.Wrapped).Distinct()],
    [.. combos.Where(c => c.Kind.StartsWith("validated", StringComparison.Ordinal)).Select(c => c.Wrapped)]
);

static string OneLine(string abbreviation, string name, Wrapped w) => abbreviation switch
{
    "rs" => $"public readonly partial record struct {name} : IValue<{w.Type}>;",
    "rc" => $"public sealed partial record class {name} : IValue<{w.Type}>;",
    _ => $"public {(abbreviation == "vs" ? "readonly partial record struct" : "sealed partial record class")} {name} : IValidatedValue<{name}, {w.Type}, ShapeFault> " +
         $"{{ public static Result<{name}, ShapeFault> Create({w.Type} value) => EqualityComparer<{w.Type}>.Default.Equals(value, {w.Refused}) ? Result.Error(ShapeFault.Refused) : new {name}(value); }}",
};

static IEnumerable<(string Kind, string Abbreviation)> KindsFor(string key, HashSet<string> validated) =>
    Grids.Kinds.Where(k => k.Abbreviation is "rs" or "rc" || validated.Contains(key));

static string TopLevel(List<(string Kind, string Wrapped, string Site)> combos)
{
    var (wrapped, validated) = Grid(combos);
    var o = new List<string>
    {
        "// <auto-generated/> by tools/probe/generators/ef.cs top-level: top-level shapes for every (kind, wrapped) the E03/E09/E10 probes need. Do not edit.",
        "#nullable enable", Grids.Pragmas,
        "using CodoMetis.TypeKit;", "using CodoMetis.TypeKit.ValueObjects;", "using Probes.Shapes;", "namespace Probes.Ef3;",
    };
    foreach (var key in wrapped)
        foreach (var (_, p) in KindsFor(key, validated))
            o.Add(OneLine(p, $"X_{p}_{Ident(key)}", Wrapped.Of(key)));
    o.Add("public static class Reg3 {");
    o.Add(" public static readonly Dictionary<(string Kind, string Wrapped), (Type Vo, Type Plain)> All = new() {");
    foreach (var key in wrapped)
        foreach (var (kind, p) in KindsFor(key, validated))
            o.Add($"  [(\"{kind}\", \"{key}\")] = (typeof(X_{p}_{Ident(key)}), typeof({Wrapped.Of(key).Type})),");
    o.Add(" };");
    o.Add("}");
    return string.Join("\n", o) + "\n";
}

static string Nested(List<(string Kind, string Wrapped, string Site)> combos)
{
    var (wrapped, validated) = Grid(combos);
    var o = new List<string>
    {
        "// <auto-generated/> by tools/probe/generators/ef.cs nested: nested-site shapes (nested-in-class, nested-in-struct, nested-two-levels) for every kind x wrapped. Do not edit.",
        "#nullable enable", Grids.Pragmas,
        "using CodoMetis.TypeKit;", "using CodoMetis.TypeKit.ValueObjects;", "using Probes.Shapes;", "namespace Probes.Ef4;",
    };
    var registry = new List<string>();
    foreach (var key in wrapped)
    {
        var w = Wrapped.Of(key);
        foreach (var (kind, p) in KindsFor(key, validated))
        {
            var decl = OneLine(p, "V", w);
            var n = $"{p}_{Ident(key)}";
            o.Add($"public static class NC_{n} {{ {decl} }}");
            o.Add($"public struct NS_{n} {{ {decl} }}");
            o.Add($"public static class N2_{n} {{ public static class Inner {{ {decl} }} }}");
            foreach (var (site, path) in new[] { ("nested-in-class", $"NC_{n}.V"), ("nested-in-struct", $"NS_{n}.V"), ("nested-two-levels", $"N2_{n}.Inner.V") })
                registry.Add($"  [(\"{kind}\", \"{key}\", \"{site}\")] = (typeof({path}), typeof({w.Type})),");
        }
    }
    o.Add("public static class Reg4 {");
    o.Add(" public static readonly Dictionary<(string Kind, string Wrapped, string Site), (Type Vo, Type Plain)> All = new() {");
    o.AddRange(registry);
    o.Add(" };");
    o.Add("}");
    return string.Join("\n", o) + "\n";
}

static string Ident(string s) => s.Replace('-', '_').Replace('.', '_');

static string Arg(string[] args, string name)
{
    var at = Array.IndexOf(args, name);
    return at >= 0 && at + 1 < args.Length ? args[at + 1] : throw new GeneratorError($"{name} <path> is required");
}

// Every --rows file's rows, in order, each cut to the --first n that follows it.
static IEnumerable<Dictionary<string, string>> RowsArguments(string[] args)
{
    var any = false;
    for (var i = 1; i < args.Length; i++)
    {
        if (args[i] != "--rows") continue;
        if (i + 1 >= args.Length) throw new GeneratorError("--rows <path> needs a path");
        var rows = Rows(args[i + 1]);
        if (i + 3 < args.Length && args[i + 2] == "--first")
        {
            var first = int.Parse(args[i + 3], System.Globalization.CultureInfo.InvariantCulture);
            if (first > rows.Count) throw new GeneratorError($"--first {first}, but {args[i + 1]} holds {rows.Count} rows");
            rows = rows.GetRange(0, first);
        }
        any = true;
        foreach (var row in rows) yield return row;
    }
    if (!any) throw new GeneratorError("at least one --rows <path> is required");
}

// A rows file of `prober rows`: gzipped JSON, {"claim": ..., "rows": [{"row": {axis: value}}, ...]}.
static List<Dictionary<string, string>> Rows(string path)
{
    using var gzip = new GZipStream(File.OpenRead(path), CompressionMode.Decompress);
    var rows = JsonNode.Parse(gzip)?["rows"] as JsonArray ?? throw new GeneratorError($"{path} has no rows");
    return
    [
        .. rows.Select(r => (r?["row"] as JsonObject ?? throw new GeneratorError($"{path}: an entry without a row"))
                   .ToDictionary(p => p.Key, p => p.Value?.GetValue<string>() ?? throw new GeneratorError($"{path}: {p.Key} is null"), StringComparer.Ordinal)),
    ];
}

/// <summary>A wrapped type: its C# spelling, a value Create keeps and the one it refuses.</summary>
sealed record Wrapped(string Type, string Valid, string Refused)
{
    static readonly Dictionary<string, Wrapped> Table = new(StringComparer.Ordinal)
    {
        ["string"] = new("string", "\"alpha\"", "\"SECRET-7f3a\""),
        ["Guid"] = new("Guid", "Guid.Parse(\"11111111-1111-1111-1111-111111111111\")", "Guid.Empty"),
        ["int"] = new("int", "42", "-1"),
        ["long"] = new("long", "4200000000L", "-1L"),
        ["byte"] = new("byte", "(byte)7", "(byte)255"),
        ["ulong"] = new("ulong", "4200000000UL", "0UL"),
        ["decimal"] = new("decimal", "7.80m", "-1m"),
        ["double"] = new("double", "1.5", "-1.0"),
        ["bool"] = new("bool", "true", "false"),
        ["char"] = new("char", "'a'", "'x'"),
        ["DateTime"] = new("DateTime", "new DateTime(2026,10,15,8,30,0,DateTimeKind.Utc)", "DateTime.MinValue"),
        ["DateTimeOffset"] = new("DateTimeOffset", "new DateTimeOffset(2026,10,15,8,30,0,TimeSpan.Zero)", "DateTimeOffset.MinValue"),
        ["DateOnly"] = new("DateOnly", "new DateOnly(2026,10,15)", "DateOnly.MinValue"),
        ["TimeOnly"] = new("TimeOnly", "new TimeOnly(8,30,15)", "TimeOnly.MinValue"),
        ["TimeSpan"] = new("TimeSpan", "TimeSpan.FromMinutes(90)", "TimeSpan.MinValue"),
        ["enum"] = new("PEnum", "PEnum.B", "(PEnum)99"),
        ["flags-enum"] = new("PFlags", "PFlags.P | PFlags.Q", "(PFlags)0"),
        ["Uri"] = new("Uri", "new Uri(\"https://example.com/a\")", "new Uri(\"https://example.com/refused\")"),
    };

    public static Wrapped Of(string key) =>
        Table.TryGetValue(key, out var w) ? w : throw new GeneratorError($"shape.wrapped {key} is not in ef.cs's table");
}

static class Grids
{
    public const string Pragmas = "#pragma warning disable CMTK0014, CS8618, CS1591, CMTK0005, CMTK1000, CMTK0003, CMTK0006, CA1000";

    public static readonly (string Kind, string Abbreviation)[] Kinds =
        [("record-struct", "rs"), ("sealed-record-class", "rc"), ("validated-struct", "vs"), ("validated-class", "vc")];
}

sealed class GeneratorError(string message) : Exception(message);
