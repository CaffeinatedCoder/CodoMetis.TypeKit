// Writes the declarations the C09 and C11 probes build, one value object per row of the claim's rows file:
//
//   C09  C09Shapes.g.cs  each row's base records (their own equality under base-equality) and the value object over them
//   C11  C11Shapes.g.cs  each row's value object over its parse-shape's wrapped type, with a control that parses where one exists
//
//   dotnet run tools/probe/generators/decls.cs -- C09 --rows tools/probe/corpus/rows/C09-base-record-equality.json.gz \
//       --out tools/probe/corpus/harness/C09Shapes.g.cs
//   dotnet run tools/probe/generators/decls.cs -- C11 --rows tools/probe/corpus/rows/C11-parse-shapes-build.json.gz \
//       --out tools/probe/corpus/harness/C11Shapes.g.cs
//
// A row's excluded values are replaced by the nearest that exists; the table names the effective settings and the row's
// own key, which the probe checks against the rows file it runs (a stale file is a harness error). A rows file is gzipped
// JSON, written by `prober rows`. GeneratedHarnessTests in the conventions tests holds each file to this output.
using System.IO.Compression;
using System.Text;
using System.Text.Json.Nodes;

try
{
    var mode = args.Length > 0 ? args[0] : throw new GeneratorError("a mode is required: C09 or C11");
    var (claim, rows) = Rows(Arg(args, "--rows"));
    if (!claim.StartsWith(mode + "-", StringComparison.Ordinal)) throw new GeneratorError($"mode {mode} reads {mode}'s rows, not {claim}'s");
    var text = mode switch
    {
        "C09" => C09(claim, rows),
        "C11" => C11(claim, rows),
        _ => throw new GeneratorError($"unknown mode {mode}"),
    };
    File.WriteAllText(Arg(args, "--out"), text, new UTF8Encoding(false));
    return 0;
}
catch (GeneratorError e)
{
    Console.Error.WriteLine($"decls.cs: {e.Message}");
    return 2;
}

static string Head(string claim, string ns) =>
    $"// <auto-generated/> by tools/probe/generators/decls.cs from rows/{claim}.json.gz: one value object per row. Do not edit; regenerate with the rows.\n" +
    "#nullable enable\n" +
    "// CMTK1023: the bases' own equality is the point (C09) or beside it (C11); CS8851: a base's Equals without GetHashCode, on purpose.\n" +
    "#pragma warning disable CMTK1023, CS8851, CS1591\n" +
    "using CodoMetis.TypeKit;\n" +
    "using CodoMetis.TypeKit.ValueObjects;\n" +
    $"namespace Probes.Build.{ns};\n";

// The row's own key: every axis=value, sorted by axis.
static string Key(Dictionary<string, string> row) => string.Join(";", row.Keys.Order(StringComparer.Ordinal).Select(k => $"{k}={row[k]}"));

// The declarations at the row's site, and the qualifier that reaches them from the namespace.
static (string Text, string Qualifier) AtSite(string site, int idx, string inner) => site switch
{
    "top-level" => (inner, ""),
    "nested-in-class" => ($"public static partial class O{idx}\n{{\n{inner}}}\n", $"O{idx}."),
    "nested-in-struct" => ($"public partial struct O{idx}\n{{\n{inner}}}\n", $"O{idx}."),
    "nested-two-levels" => ($"public static partial class O{idx}\n{{\npublic sealed partial class P{idx}\n{{\n{inner}}}\n}}\n", $"O{idx}.P{idx}."),
    _ => throw new GeneratorError($"shape.site {site} has no site here"),
};

// How many base records an inheritance puts under the value object.
static int Depth(string inheritance) => inheritance switch
{
    "base-depth-2" => 2,
    "base-depth-3" => 3,
    "base-depth-1" or "base-explicit-IEquatable" or "explicit-interface-member" => 1,
    _ => 0,
};

static string Record(string name, List<string> parents, List<string> members) =>
    $"public abstract record {name}" + (parents.Count > 0 ? " : " + string.Join(", ", parents) : "") + " { " + string.Join(" ", members) + " }";

static string Substitutions(List<(string Axis, string Value)> subs) => string.Join(", ", subs.Select(s => $"(\"{s.Axis}\", \"{s.Value}\")"));

static string Table(string name, string caseType, List<string> table) =>
    $"public static partial class {name}\n{{\n    public static readonly {caseType}[] Cases =\n    [\n" + string.Join("\n", table) + "\n    ];\n}\n";

static string C09(string claim, List<Dictionary<string, string>> rows)
{
    var o = new List<string> { Head(claim, "C09") };
    var table = new List<string>();
    for (var idx = 0; idx < rows.Count; idx++)
    {
        var row = rows[idx];
        var subs = new List<(string, string)>();
        var kind = row["shape.kind"];
        if (kind is "record-struct" or "closed-set") { subs.Add(("shape.kind", "sealed-record-class")); kind = "sealed-record-class"; }
        else if (kind == "validated-struct") { subs.Add(("shape.kind", "validated-class")); kind = "validated-class"; }
        var site = row["shape.site"];
        if (site == "in-generic-type") { subs.Add(("shape.site", "nested-in-class")); site = "nested-in-class"; }
        var inh = row["shape.inheritance"];
        if (inh == "none") { subs.Add(("shape.inheritance", "base-depth-1")); inh = "base-depth-1"; }
        var eq = row["base-equality"];
        var w = WrappedType(row["shape.wrapped"]);

        var n = Depth(inh);
        var body = new List<string>();
        if (inh == "explicit-interface-member") body.Add($"public interface IMark{idx} {{ int Mark(); }}");
        for (var d = n; d >= 1; d--)
        {
            var name = $"B{idx}_{d}";
            var parents = d == n ? new List<string>() : [$"B{idx}_{d + 1}"];
            var members = new List<string>();
            if (d == n)
            {
                // the deepest base carries the row's own equality
                if (eq == "override-Equals") members.Add($"public virtual bool Equals({name}? other) => ReferenceEquals(this, other);");
                else if (eq == "override-GetHashCode") members.Add("public override int GetHashCode() => System.Runtime.CompilerServices.RuntimeHelpers.GetHashCode(this);");
                else if (eq == "explicit-IEquatable")
                {
                    parents.Add($"System.IEquatable<{name}>");
                    members.Add($"bool System.IEquatable<{name}>.Equals({name}? other) => ReferenceEquals(this, other);");
                }
            }
            if (d == 1 && inh == "base-explicit-IEquatable" && !(eq == "explicit-IEquatable" && n == 1))
            {
                parents.Add($"System.IEquatable<{name}>");
                members.Add($"bool System.IEquatable<{name}>.Equals({name}? other) => ReferenceEquals(this, other);");
            }
            if (d == 1 && inh == "explicit-interface-member")
            {
                parents.Add($"IMark{idx}");
                members.Add($"int IMark{idx}.Mark() => 1;");
            }
            body.Add(Record(name, parents, members));
        }
        var v = $"V{idx}";
        string make;
        if (kind == "validated-class")
        {
            body.Add($"public sealed partial record {v} : B{idx}_1, IValidatedValue<{v}, {w}, global::Probes.Shapes.ShapeFault>\n{{\n" +
                     $"    public static Result<{v}, global::Probes.Shapes.ShapeFault> Create({w} value) => new {v}(value);\n}}");
            make = $"{v}.FromKnownGood(({w})x)";
        }
        else
        {
            body.Add($"public sealed partial record {v} : B{idx}_1, IValue<{w}>;");
            make = $"{v}.From(({w})x)";
        }
        var (text, q) = AtSite(site, idx, string.Join("\n", body) + "\n");
        o.Add($"// row {idx}\n" + text);
        var bases = string.Join(", ", Enumerable.Range(1, n).Select(d => $"typeof({q}B{idx}_{d})"));
        table.Add($"        new({idx}, \"{Key(row)}\", \"{kind}\", \"{site}\", \"{inh}\", typeof({q}{v}), [{bases}], x => {q}{make}, [{Substitutions(subs)}]),");
    }
    o.Add(Table("C09Table", "C09Case", table));
    return string.Join("\n", o);
}

static string C11(string claim, List<Dictionary<string, string>> rows)
{
    // A parse shape's control (a wrapped type of the same shape that parses) and its odd wrapped type.
    var control = new Dictionary<string, string>(StringComparer.Ordinal)
    {
        ["implicit-result"] = "global::Probes.Build.C11ParsedShape",
        ["ref-text"] = "global::Probes.Build.C11ParsesFromIn",
        ["abstract-string-ctor"] = "global::Probes.Build.C11ConstructedConcrete",
    };
    var odd = new Dictionary<string, string>(StringComparer.Ordinal)
    {
        ["implicit-result"] = "global::Probes.Build.C11ParsesToInt",
        ["abstract-string-ctor"] = "global::Probes.Build.C11AbstractText",
    };
    const string fault = "global::Probes.Shapes.ShapeFault";

    var o = new List<string> { Head(claim, "C11") };
    var table = new List<string>();
    for (var idx = 0; idx < rows.Count; idx++)
    {
        var row = rows[idx];
        var subs = new List<(string, string)>();
        var kind = row["shape.kind"];
        if (kind == "closed-set") { subs.Add(("shape.kind", "sealed-record-class")); kind = "sealed-record-class"; }
        var site = row["shape.site"];
        if (site == "in-generic-type") { subs.Add(("shape.site", "nested-in-class")); site = "nested-in-class"; }
        var inh = row["shape.inheritance"];
        var isStruct = kind is "record-struct" or "validated-struct";
        if (isStruct && inh is not ("none" or "explicit-interface-member")) { subs.Add(("shape.inheritance", "none")); inh = "none"; }
        var shape = row["parse-shape"];
        var w = shape switch
        {
            "ordinary" => WrappedType(row["shape.wrapped"]),
            "ref-text" => idx % 2 == 0 ? "global::Probes.Build.C11ParsesByRef" : "global::Probes.Build.C11ConstructedByRef",
            _ => odd.TryGetValue(shape, out var t) ? t : throw new GeneratorError($"parse-shape {shape} has no wrapped type here"),
        };
        var n = isStruct || inh == "explicit-interface-member" ? 0 : Depth(inh);
        var body = new List<string>();
        if (inh == "explicit-interface-member") body.Add($"public interface IMark{idx} {{ int Mark(); }}");

        void Declare(string v, string b, string wrapped)
        {
            var mark = inh == "explicit-interface-member" ? $", IMark{idx}" : "";
            for (var d = n; d >= 1; d--)
            {
                var name = $"{b}{idx}_{d}";
                var parents = d == n ? new List<string>() : [$"{b}{idx}_{d + 1}"];
                var members = new List<string>();
                if (d == 1 && inh == "base-explicit-IEquatable")
                {
                    parents.Add($"System.IEquatable<{name}>");
                    members.Add($"bool System.IEquatable<{name}>.Equals({name}? other) => ReferenceEquals(this, other);");
                }
                body.Add(Record(name, parents, members));
            }
            var @base = n > 0 ? $"{b}{idx}_1, " : "";
            var m = mark != "" ? $" int IMark{idx}.Mark() => 1;" : "";
            body.Add(kind switch
            {
                "record-struct" => $"public readonly partial record struct {v} : IValue<{wrapped}>{mark} {{{m} }}",
                "sealed-record-class" => $"public sealed partial record {v} : {@base}IValue<{wrapped}>{mark} {{{m} }}",
                "validated-struct" => $"public readonly partial record struct {v} : IValidatedValue<{v}, {wrapped}, {fault}>{mark}\n{{\n" +
                                      $"    public static Result<{v}, {fault}> Create({wrapped} value) => new {v}(value);{m}\n}}",
                "validated-class" => $"public sealed partial record {v} : {@base}IValidatedValue<{v}, {wrapped}, {fault}>{mark}\n{{\n" +
                                     $"    public static Result<{v}, {fault}> Create({wrapped} value) => new {v}(value);{m}\n}}",
                _ => throw new GeneratorError($"shape.kind {kind} has no declaration here"),
            });
        }

        var v = $"V{idx}";
        Declare(v, "B", w);
        var c = control.GetValueOrDefault(shape);
        if (c is not null) Declare($"VC{idx}", "BC", c);
        var (text, q) = AtSite(site, idx, string.Join("\n", body) + "\n");
        o.Add($"// row {idx}\n" + text);
        var ctl = c is not null ? $"typeof({q}VC{idx}), typeof({c})" : "null, null";
        table.Add($"        new({idx}, \"{Key(row)}\", \"{kind}\", \"{site}\", \"{inh}\", typeof({q}{v}), typeof({w}), {ctl}, [{Substitutions(subs)}]),");
    }
    o.Add(Table("C11Table", "C11Case", table));
    return string.Join("\n", o);
}

static string WrappedType(string key) => key switch
{
    "string" => "string", "Guid" => "global::System.Guid", "int" => "int", "long" => "long", "byte" => "byte", "ulong" => "ulong",
    "decimal" => "decimal", "double" => "double", "bool" => "bool", "char" => "char", "DateTime" => "global::System.DateTime",
    "DateTimeOffset" => "global::System.DateTimeOffset", "DateOnly" => "global::System.DateOnly", "TimeOnly" => "global::System.TimeOnly",
    "TimeSpan" => "global::System.TimeSpan", "enum" => "global::Probes.Shapes.PEnum", "flags-enum" => "global::Probes.Shapes.PFlags",
    "Uri" => "global::System.Uri", "NodaTime.Instant" => "global::NodaTime.Instant", "own-record-class" => "global::Probes.Shapes.PRec",
    _ => throw new GeneratorError($"shape.wrapped {key} is not in decls.cs's table"),
};

static string Arg(string[] args, string name)
{
    var at = Array.IndexOf(args, name);
    return at >= 0 && at + 1 < args.Length ? args[at + 1] : throw new GeneratorError($"{name} <path> is required");
}

// A rows file of `prober rows`: gzipped JSON, {"claim": ..., "rows": [{"row": {axis: value}}, ...]}.
static (string Claim, List<Dictionary<string, string>> Rows) Rows(string path)
{
    using var gzip = new GZipStream(File.OpenRead(path), CompressionMode.Decompress);
    var document = JsonNode.Parse(gzip) ?? throw new GeneratorError($"{path} is empty");
    var claim = document["claim"]?.GetValue<string>() ?? throw new GeneratorError($"{path} names no claim");
    var rows = document["rows"] as JsonArray ?? throw new GeneratorError($"{path} has no rows");
    return (claim,
    [
        .. rows.Select(r => (r?["row"] as JsonObject ?? throw new GeneratorError($"{path}: an entry without a row"))
                   .ToDictionary(p => p.Key, p => p.Value?.GetValue<string>() ?? throw new GeneratorError($"{path}: {p.Key} is null"), StringComparer.Ordinal)),
    ]);
}

sealed class GeneratorError(string message) : Exception(message);
