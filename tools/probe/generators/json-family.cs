// Writes the JSON family's declarations from its rows, one mode per file of tools/probe/corpus/harness:
//
//   contexts  JsonFamilyShapes.g.cs  the source-generated contexts of C01, C10 and L06 (each lists exactly the shapes of
//                                    its rows that run under json.TypeInfoResolver=source-generated-context), and L06's
//                                    polymorphic stand-ins over Option and Result
//   l05       L05Shapes.g.cs         L05's value objects and closed sets, one per (kind, wrapped, inheritance, site) its
//                                    rows name, and L05Registry
//
//   dotnet run tools/probe/generators/json-family.cs -- contexts --out tools/probe/corpus/harness/JsonFamilyShapes.g.cs \
//       --c01 tools/probe/corpus/rows/C01-decimal-spelling.json.gz --c10 tools/probe/corpus/rows/C10-preserve-guard.json.gz \
//       --l06 tools/probe/corpus/rows/L06-off-the-wire.json.gz
//   dotnet run tools/probe/generators/json-family.cs -- l05 --out tools/probe/corpus/harness/L05Shapes.g.cs \
//       --rows tools/probe/corpus/rows/L05-equality.json.gz
//
// A rows file is gzipped JSON, written by `prober rows`. GeneratedHarnessTests in the conventions tests holds each
// file to this output.
using System.IO.Compression;
using System.Text;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;

try
{
    var mode = args.Length > 0 ? args[0] : throw new GeneratorError("a mode is required: contexts or l05");
    var text = mode switch
    {
        "contexts" => Contexts(Rows(Arg(args, "--c01")), Rows(Arg(args, "--c10")), Rows(Arg(args, "--l06"))),
        "l05" => L05(Rows(Arg(args, "--rows"))),
        _ => throw new GeneratorError($"unknown mode {mode}"),
    };
    File.WriteAllText(Arg(args, "--out"), text, new UTF8Encoding(false));
    return 0;
}
catch (GeneratorError e)
{
    Console.Error.WriteLine($"json-family.cs: {e.Message}");
    return 2;
}

static string Contexts(List<Dictionary<string, string>> c01, List<Dictionary<string, string>> c10, List<Dictionary<string, string>> l06)
{
    var contexts = new List<(string Name, HashSet<string> Types)>();

    // C01: the decimal and the value object over one
    var types = new HashSet<string>(StringComparer.Ordinal);
    foreach (var r in c01.Where(SourceGenerated))
    {
        var (k, p, c) = (r["shape.kind"], r["shape.position"], ContainerOf(r));
        if (k == "closed-set") continue;
        types.Add(Shape.Holder(p, c, "decimal", true, "PBP_decimal"));
        types.Add(Shape.Holder(p, c, Shape.Vo(k, "decimal"), Shape.VoIsStruct(k), Shape.Poly(k, "decimal", true)));
    }
    contexts.Add(("C01JsonContext", types));

    // C10: the wrapped type and the value object
    types = new HashSet<string>(StringComparer.Ordinal);
    foreach (var r in c10.Where(SourceGenerated))
    {
        var (k, w, p, c) = (r["shape.kind"], r["shape.wrapped"], r["shape.position"], ContainerOf(r));
        types.Add(Shape.Holder(p, c, Shape.Plain(k, w), Shape.PlainIsStruct(k, w), Shape.Poly(k, w, false)));
        types.Add(Shape.Holder(p, c, Shape.Vo(k, w), Shape.VoIsStruct(k), Shape.Poly(k, w, true)));
    }
    contexts.Add(("C10JsonContext", types));

    // L06: the value object (whose document is the read's input) and the Option or Result over it
    types = new HashSet<string>(StringComparer.Ordinal);
    foreach (var r in l06.Where(SourceGenerated))
    {
        var (k, w, p, c, s) = (r["shape.kind"], r["shape.wrapped"], r["shape.position"], ContainerOf(r), r["or.shape"]);
        var v = Shape.Vo(k, w);
        types.Add(Shape.Holder(p, c, v, Shape.VoIsStruct(k), Shape.Poly(k, w, true)));
        types.Add(Shape.Holder(p, c, Carrier.Type(s, v), true, Carrier.Poly(s, v)));
        types.Add(Shape.Plain(k, w));   // the wrapped type, as an application lists it (Generators README#json: a context sees no further than a converter)
    }
    contexts.Add(("L06JsonContext", types));

    var o = new List<string>
    {
        "// <auto-generated/> by tools/probe/generators/json-family.cs from the rows of C01, C10 and L06. Do not edit.",
        "#nullable disable", "#pragma warning disable CS8618, CS1591, CMTK0005, CMTK0006",
        "using System.Collections.Immutable;", "using System.Text.Json.Serialization;", "using CodoMetis.TypeKit;", "using Probes.Shapes;",
        "namespace Probes.Json;", "",
    };
    // L06's polymorphic stand-ins: a base per value object and carrier, its derived type holding the Option or Result
    var vos = new[] { "record-struct", "sealed-record-class", "validated-struct", "validated-class" }
        .SelectMany(k => Shape.WrappedTypes.Keys.Select(w => Shape.Vo(k, w))).Append("PSet");
    foreach (var v in vos)
    {
        foreach (var (key, pattern) in new[] { ("O", "Option<{0}>"), ("RTE", "Result<{0}, ShapeFault>"), ("RE", "Result<{0}>") })
        {
            var (b, d) = ($"L06PB_{Shape.San(v)}_{key}", $"L06PD_{Shape.San(v)}_{key}");
            o.Add($"[JsonPolymorphic] [JsonDerivedType(typeof({d}), \"d\")] public abstract class {b} {{ }}");
            o.Add($"public sealed class {d} : {b} {{ public {string.Format(System.Globalization.CultureInfo.InvariantCulture, pattern, v)} Value {{ get; set; }} }}");
        }
    }
    o.Add("");
    foreach (var (name, ts) in contexts)
    {
        var i = 0;
        foreach (var t in ts.Order(StringComparer.Ordinal))
        {
            // a generic or array shape gets a name of its own (two would collide); a plain type keeps the serializer's (its built-in converter)
            o.Add(t.Contains('<') || t.Contains('[') ? $"[JsonSerializable(typeof({t}), TypeInfoPropertyName = \"T{i}\")]" : $"[JsonSerializable(typeof({t}))]");
            i++;
        }
        o.Add($"public partial class {name} : JsonSerializerContext {{ }}");
        o.Add("");
    }
    return string.Join("\n", o);
}

static bool SourceGenerated(Dictionary<string, string> r) => r.GetValueOrDefault("json.TypeInfoResolver") == "source-generated-context";

static string ContainerOf(Dictionary<string, string> r) => r["shape.position"] == "root" ? "class" : r["shape.containing"];

static string L05(List<Dictionary<string, string>> rows)
{
    // A row the covering array made with an excluded pair runs the nearest shape that exists (the probe notes the substitution).
    static string SiteOf(Dictionary<string, string> r) => r["shape.site"] == "in-generic-type" ? "top-level" : r["shape.site"];
    static string InheritanceOf(Dictionary<string, string> r) =>
        Shape.VoIsStruct(r["shape.kind"]) && r["shape.inheritance"].StartsWith("base-", StringComparison.Ordinal) ? "none" : r["shape.inheritance"];

    var tuples = rows
        .Select(r => (Kind: r["shape.kind"], Wrapped: r["shape.kind"] == "closed-set" ? "-" : r["shape.wrapped"], Inheritance: InheritanceOf(r), Site: SiteOf(r)))
        .Distinct()
        .OrderBy(t => t.Kind, StringComparer.Ordinal).ThenBy(t => t.Wrapped, StringComparer.Ordinal)
        .ThenBy(t => t.Inheritance, StringComparer.Ordinal).ThenBy(t => t.Site, StringComparer.Ordinal)
        .ToList();

    var o = new List<string>
    {
        "// <auto-generated/> by tools/probe/generators/json-family.cs from the rows of L05-equality. Do not edit.",
        "#nullable enable",
        "#pragma warning disable CS1591, CMTK0005, CMTK1023 // CMTK1023: a base record with an explicit IEquatable is the shape under test",
        "using CodoMetis.TypeKit;", "using CodoMetis.TypeKit.ValueObjects;", "using CodoMetis.TypeKit.ClosedSets;", "using Probes.Shapes;",
        "namespace Probes.Json;", "",
        "public interface IL05Tag { string Tag { get; } }",
        "public abstract record L05B1;", "public abstract record L05B2a;", "public abstract record L05B2b : L05B2a;",
        "public abstract record L05B3a;", "public abstract record L05B3b : L05B3a;", "public abstract record L05B3c : L05B3b;",
        "// a deeper base whose own IEquatable says \"never equal\": the value object must not use it",
        "public abstract record L05E0 : IEquatable<L05E0> { bool IEquatable<L05E0>.Equals(L05E0? other) => false; }",
        "public abstract record L05E1 : L05E0;",
        "public abstract class L05CB1;", "public abstract class L05CB2a;", "public abstract class L05CB2b : L05CB2a;",
        "public abstract class L05CB3a;", "public abstract class L05CB3b : L05CB3a;", "public abstract class L05CB3c : L05CB3b;",
        "public abstract class L05CE0 : IEquatable<L05CE0> { bool IEquatable<L05CE0>.Equals(L05CE0? other) => ReferenceEquals(this, other); }",
        "public abstract class L05CE1 : L05CE0;", "",
    };
    // the base each inheritance names: records under a value object, classes under a closed set
    var recordBases = new Dictionary<string, string>(StringComparer.Ordinal)
        { ["base-depth-1"] = "L05B1", ["base-depth-2"] = "L05B2b", ["base-depth-3"] = "L05B3c", ["base-explicit-IEquatable"] = "L05E1" };
    var classBases = new Dictionary<string, string>(StringComparer.Ordinal)
        { ["base-depth-1"] = "L05CB1", ["base-depth-2"] = "L05CB2b", ["base-depth-3"] = "L05CB3c", ["base-explicit-IEquatable"] = "L05CE1" };

    var registry = new List<string>();
    for (var i = 0; i < tuples.Count; i++)
    {
        var (k, w, inh, site) = tuples[i];
        var n = $"L05_{i}_{Shape.San(k)}_{Shape.San(w)}";
        var bases = new List<string>();
        if (inh.StartsWith("base-", StringComparison.Ordinal)) bases.Add((k == "closed-set" ? classBases : recordBases)[inh]);
        var tag = inh == "explicit-interface-member" ? " string IL05Tag.Tag => \"t\";" : "";
        if (inh == "explicit-interface-member") bases.Add("IL05Tag");
        var head = string.Concat(bases.Select(b => b + ", "));
        string decl;
        if (k == "closed-set")
            decl = $"public sealed partial class {n} : {head}IClosedSet<{n}> {{ public static readonly {n} Alpha = new(); public static readonly {n} Beta = new();{tag} }}";
        else
        {
            var t = Shape.WrappedTypes[w];
            decl = k switch
            {
                "record-struct" => $"public readonly partial record struct {n} : {head}IValue<{t}> {{{tag} }}",
                "sealed-record-class" => $"public sealed partial record {n} : {head}IValue<{t}> {{{tag} }}",
                "validated-struct" => $"public readonly partial record struct {n} : {head}IValidatedValue<{n}, {t}, ShapeFault> {{ public static Result<{n}, ShapeFault> Create({t} value) => new {n}(value);{tag} }}",
                "validated-class" => $"public sealed partial record {n} : {head}IValidatedValue<{n}, {t}, ShapeFault> {{ public static Result<{n}, ShapeFault> Create({t} value) => new {n}(value);{tag} }}",
                _ => throw new GeneratorError($"shape.kind {k} has no declaration here"),
            };
        }
        string full;
        switch (site)
        {
            case "top-level": o.Add(decl); full = n; break;
            case "nested-in-class": o.Add($"public partial class L05Oc{i} {{ {decl} }}"); full = $"L05Oc{i}.{n}"; break;
            case "nested-in-struct": o.Add($"public partial struct L05Os{i} {{ {decl} }}"); full = $"L05Os{i}.{n}"; break;
            case "nested-two-levels": o.Add($"public partial class L05Ot{i} {{ public partial class Inner {{ {decl} }} }}"); full = $"L05Ot{i}.Inner.{n}"; break;
            default: throw new GeneratorError($"shape.site {site} has no shape here");
        }
        if (k == "closed-set")
            registry.Add($"        Add(\"{k}\", \"-\", \"{inh}\", \"{site}\", typeof({full}), () => {full}.Alpha, () => {full}.All.First(m => m.Name == \"Alpha\"), () => {full}.Beta);");
        else
        {
            var (a1, a2, b) = L05Samples.All[w];
            registry.Add($"        Add(\"{k}\", \"{w}\", \"{inh}\", \"{site}\", typeof({full}), () => {a1}, () => {a2}, () => {b});");
        }
    }
    o.AddRange(["", "public static partial class L05Registry", "{", "    static partial void Fill()", "    {"]);
    o.AddRange(registry);
    o.AddRange(["    }", "}", ""]);
    return string.Join("\n", o);
}

static string Arg(string[] args, string name)
{
    var at = Array.IndexOf(args, name);
    return at >= 0 && at + 1 < args.Length ? args[at + 1] : throw new GeneratorError($"{name} <path> is required");
}

// A rows file of `prober rows`: gzipped JSON, {"claim": ..., "rows": [{"row": {axis: value}}, ...]}.
static List<Dictionary<string, string>> Rows(string path)
{
    using var gzip = new GZipStream(File.OpenRead(path), CompressionMode.Decompress);
    var rows = JsonNode.Parse(gzip)?["rows"] as JsonArray ?? throw new GeneratorError($"{path} has no rows");
    return
    [
        .. rows.Select(r => (r?["row"] as JsonObject ?? throw new GeneratorError($"{path}: an entry without a row"))
                   .ToDictionary(p => p.Key, p => p.Value?.GetValue<string>() ?? throw new GeneratorError($"{path}: {p.Key} is null"), StringComparer.Ordinal)),
    ];
}

