/// <summary>The names the shapes of Shapes.g.cs and Containers.g.cs go by, and how a row's position holds one.</summary>
static partial class Shape
{
    /// <summary>Each wrapped type's C# spelling, in the axes file's order.</summary>
    public static readonly Dictionary<string, string> WrappedTypes = new(StringComparer.Ordinal)
    {
        ["string"] = "string", ["Guid"] = "Guid", ["int"] = "int", ["long"] = "long", ["byte"] = "byte", ["ulong"] = "ulong",
        ["decimal"] = "decimal", ["double"] = "double", ["bool"] = "bool", ["char"] = "char", ["DateTime"] = "DateTime",
        ["DateTimeOffset"] = "DateTimeOffset", ["DateOnly"] = "DateOnly", ["TimeOnly"] = "TimeOnly", ["TimeSpan"] = "TimeSpan",
        ["enum"] = "PEnum", ["flags-enum"] = "PFlags", ["Uri"] = "Uri", ["NodaTime.Instant"] = "global::NodaTime.Instant",
        ["own-record-class"] = "PRec",
    };

    static readonly HashSet<string> Classes = new(StringComparer.Ordinal) { "string", "Uri", "own-record-class" };

    public static string San(string s) => NotAlphanumeric().Replace(s, "_");

    public static string Vo(string kind, string wrapped) => kind == "closed-set" ? "PSet" : $"V_{San(kind)}_{San(wrapped)}";

    public static bool VoIsStruct(string kind) => kind is "record-struct" or "validated-struct";

    public static string Plain(string kind, string wrapped) => kind == "closed-set" ? "string" : Wrapped(wrapped);

    public static bool PlainIsStruct(string kind, string wrapped) => kind != "closed-set" && !Classes.Contains(wrapped);

    public static string Poly(string kind, string wrapped, bool isVo) =>
        isVo ? kind == "closed-set" ? "PB_PSet" : $"PB_{Vo(kind, wrapped)}"
             : kind == "closed-set" ? "PBP_string_" : $"PBP_{San(wrapped)}";

    /// <summary>The type a row's position holds m in: m itself at the root, else a container of Containers.g.cs.</summary>
    public static string Holder(string position, string containing, string m, bool isStruct, string polyBase)
    {
        if (position == "root") return m;
        var style = position switch { "field" => "F", "record-ctor-parameter" => "C", "required-init" => "R", _ => "P" };
        var member = position switch
        {
            "nullable-property" => isStruct ? m + "?" : m,
            "list-element" => $"List<{m}>",
            "read-only-list-element" => $"IReadOnlyList<{m}>",
            "array-element" => $"{m}[]",
            "immutable-array-element" => $"ImmutableArray<{m}>",
            "dictionary-key" => $"Dictionary<{m}, int>",
            "dictionary-value" => $"Dictionary<string, {m}>",
            "in-patch" => $"Patch<{m}>",
            "polymorphic-derived-property" => polyBase,
            _ => m,
        };
        var n = containing.Replace('-', '_');
        return containing == "generic-type" ? $"Cn_{n}_{style}<{member}, int>" : $"Cn_{n}_{style}<{member}>";
    }

    static string Wrapped(string key) =>
        WrappedTypes.TryGetValue(key, out var t) ? t : throw new GeneratorError($"shape.wrapped {key} is not in json-family.cs's table");

    [GeneratedRegex("[^A-Za-z0-9]")]
    private static partial Regex NotAlphanumeric();
}

/// <summary>L06's carriers (or.shape): the Option or Result over a value object, and its polymorphic stand-in.</summary>
static class Carrier
{
    static readonly Dictionary<string, (string Key, string Pattern)> Shapes = new(StringComparer.Ordinal)
    {
        ["Option"] = ("O", "Option<{0}>"),
        ["Result-T-E"] = ("RTE", "Result<{0}, ShapeFault>"),
        ["Task-of-Result"] = ("RTE", "Result<{0}, ShapeFault>"),
        ["ValueTask-of-Result"] = ("RTE", "Result<{0}, ShapeFault>"),
        ["Result-E"] = ("RE", "Result<{0}>"),
    };

    public static string Type(string shape, string v) => string.Format(System.Globalization.CultureInfo.InvariantCulture, Of(shape).Pattern, v);

    public static string Poly(string shape, string v) => $"L06PB_{Shape.San(v)}_{Of(shape).Key}";

    static (string Key, string Pattern) Of(string shape) =>
        Shapes.TryGetValue(shape, out var s) ? s : throw new GeneratorError($"or.shape {shape} has no carrier here");
}

