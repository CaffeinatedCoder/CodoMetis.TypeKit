// Writes tools/probe/corpus/harness/FaultClaimControllers.g.cs: the MVC controllers of the fault claims C04, C06, C14
// and C15 and, from the same data, the table FxCtl that FaultClaim reads as the oracle's input (what each controller
// and action declares). Its input is the table below, not a rows file: each row of those claims picks a controller.
//
//   dotnet run tools/probe/generators/faults.cs -- --out tools/probe/corpus/harness/FaultClaimControllers.g.cs
//
// GeneratedHarnessTests in the conventions tests holds the committed file to this output.
using System.Text;

try
{
    File.WriteAllText(Arg(args, "--out"), Generate(), new UTF8Encoding(false));
    return 0;
}
catch (GeneratorError e)
{
    Console.Error.WriteLine($"faults.cs: {e.Message}");
    return 2;
}

static string Generate()
{
    // The result type an action answers, by the last segment of its route; decl answers one, with a 429 of its own.
    string[] results = ["one", "two", "dup", "decl"];
    var returns = new Dictionary<string, string>(StringComparer.Ordinal)
    {
        ["one"] = "Results<NoContent, FaultProblem<HFault>>",
        ["two"] = "Results<NoContent, FaultProblem<HFault>, FaultProblem<GFault>>",
        ["dup"] = "Results<NoContent, FaultProblem<HFault>, FaultProblem<KFault>>",
        ["decl"] = "Results<NoContent, FaultProblem<HFault>>",
    };
    var bodies = new Dictionary<string, string>(StringComparer.Ordinal)
        { ["one"] = "FxErr.One(e)", ["two"] = "FxErr.Two(e)", ["dup"] = "FxErr.Dup(e)", ["decl"] = "FxErr.One(e)" };

    var o = new List<string>
    {
        "// Generated by tools/probe/generators/faults.cs (the fault claims' MVC controllers, C04 C06 C14 C15): do not edit by hand.",
        "// Every action answers FxErr's errors; its route ends in the result type it answers (one, two, dup) or decl (one, with a",
        "// [ProducesResponseType<ProblemDetails>(429)] of its own). The table FxCtl.All restates what each class and action declares,",
        "// in ASP.NET's metadata order (controller, then action), as the input FaultClaim computes the expected response and document from.",
        "using CodoMetis.TypeKit;",
        "using CodoMetis.TypeKit.AspNetCore;",
        "using Microsoft.AspNetCore.Http;",
        "using Microsoft.AspNetCore.Http.HttpResults;",
        "using Microsoft.AspNetCore.Mvc;",
        "namespace Probes.Faults;",
        "",
    };
    foreach (var (name, variants, actions) in Table.Controllers)
    {
        o.Add($"internal abstract class Fx{name}Base : ControllerBase");
        o.Add("{");
        foreach (var (route, decls, declared) in actions)
        {
            foreach (var t in results)
            {
                var attrs = new List<string> { $"HttpGet(\"c/{route}/{t}\")" };
                attrs.AddRange(decls.Select(Attribute));
                attrs.AddRange(declared.Select(DeclaredAttribute));
                if (t == "decl") attrs.Add("ProducesResponseType<ProblemDetails>(429)");
                o.Add($"    [{string.Join(", ", attrs)}] public {returns[t]} {Pascal(route)}{char.ToUpperInvariant(t[0])}{t[1..]}(int e) => {bodies[t]}.ToHttpResult();");
            }
        }
        o.Add("}");
        foreach (var (suffix, classDecls) in variants)
        {
            var a = string.Join(", ", classDecls.Select(Attribute));
            o.Add($"[ApiController{(a != "" ? ", " + a : "")}] internal sealed class Fx{name}{suffix}Api : Fx{name}Base {{ }}");
            o.Add($"{(a != "" ? "[" + a + "] " : "")}internal sealed class Fx{name}{suffix}Plain : Fx{name}Base {{ }}");
        }
        o.Add("");
    }
    o.Add("public static partial class FxCtl");
    o.Add("{");
    o.Add("    static partial void Fill(Dictionary<string, Ctl> d)");
    o.Add("    {");
    foreach (var (name, variants, actions) in Table.Controllers)
    {
        var acts = string.Join(", ", actions.Select(x =>
            $"new(\"{x.Route}\", [{string.Join(", ", x.Decls.Select(Literal))}], [{string.Join(", ", x.Declared.Select(s => s.Status))}])"));
        foreach (var (suffix, classDecls) in variants)
            o.Add($"        d[\"{name}{suffix}\"] = new(typeof(Fx{name}{suffix}Api), typeof(Fx{name}{suffix}Plain), [{string.Join(", ", classDecls.Select(Literal))}], [{acts}]);");
    }
    o.Add("    }");
    o.Add("}");
    return string.Join("\n", o) + "\n";
}

// A fault member's status: WithoutFaults where the status is 0 (left out), FaultStatus otherwise.
static string Attribute(Decl d) => d.Status == 0 ? $"WithoutFaults<{d.Type}>(\"{d.Member}\")" : $"FaultStatus<{d.Type}>(\"{d.Member}\", {d.Status})";

static string Literal(Decl d) => $"new(\"{d.Type}\", \"{d.Member}\", {d.Status})";

// A status the action declares itself: pp as ProducesProblem declares it (with application/problem+json), prt as [ProducesResponseType] alone.
static string DeclaredAttribute(Declared x) =>
    x.How == "pp" ? $"ProducesResponseType<ProblemDetails>({x.Status}, \"application/problem+json\")" : $"ProducesResponseType<ProblemDetails>({x.Status})";

static string Pascal(string route) =>
    string.Concat(route.Split('/', StringSplitOptions.RemoveEmptyEntries).Select(p => char.ToUpperInvariant(p[0]) + p[1..]));

static string Arg(string[] args, string name)
{
    var at = Array.IndexOf(args, name);
    return at >= 0 && at + 1 < args.Length ? args[at + 1] : throw new GeneratorError($"{name} <path> is required");
}

/// <summary>A fault member's declared status on a class or an action; 0 leaves the member out.</summary>
sealed record Decl(string Type, string Member, int Status);

/// <summary>A status an action declares itself, and how.</summary>
sealed record Declared(int Status, string How);

sealed record ControllerAction(string Route, Decl[] Decls, Declared[] Declared);

