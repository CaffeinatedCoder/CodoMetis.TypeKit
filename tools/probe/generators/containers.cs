// Writes tools/probe/corpus/harness/Containers.g.cs: for each shape.containing of the axes file, one generic
// container per member style (P property, F field, C constructor parameter, R required init). The position
// (list, dictionary, ...) is the member's declared type, which the probe chooses.
//
//   dotnet run tools/probe/generators/containers.cs -- --axes .claude/probe-axes.md --out tools/probe/corpus/harness/Containers.g.cs
//
// GeneratedHarnessTests in the conventions tests holds the committed file to this output.
using System.Text;
using System.Text.Json.Nodes;

try
{
    var containing = Values(AxesBlock(Arg(args, "--axes")), "shape.containing");
    File.WriteAllText(Arg(args, "--out"), Generate(containing), new UTF8Encoding(false));
    return 0;
}
catch (GeneratorError e)
{
    Console.Error.WriteLine($"containers.cs: {e.Message}");
    return 2;
}

static string Generate(IReadOnlyList<string> containing)
{
    var o = new List<string>
    {
        "// <auto-generated/> by tools/probe/generators/containers.cs",
        "#nullable disable\n#pragma warning disable CS8618, CS1591, CS0649",
        "using System.Text.Json.Serialization;",
        "namespace Probes.Shapes;",
    };
    foreach (var c in containing)
    {
        var n = c.Replace('-', '_');
        // the declaration keyword and the type parameters; a record class takes its constructor parameter positionally
        var (keyword, parameters) = c switch
        {
            "class" => ("class", "<M>"),
            "record-class" => ("record class", "<M>"),
            "struct" => ("struct", "<M>"),
            "record-struct" => ("record struct", "<M>"),
            "generic-type" => ("class", "<M, U>"),
            _ => throw new GeneratorError($"shape.containing {c} has no container here"),
        };
        var name = $"Cn_{n}_";
        o.Add($"public {keyword} {name}P{parameters} {{ public M P {{ get; set; }} }}");
        o.Add($"public {keyword} {name}F{parameters} {{ public M F; }}");
        o.Add(c == "record-class"
            ? $"public {keyword} {name}C{parameters}(M P);"
            : $"public {keyword} {name}C{parameters} {{ public M P {{ get; }} [JsonConstructor] public {name}C(M p) {{ P = p; }} }}");
        o.Add($"public {keyword} {name}R{parameters} {{ public required M P {{ get; init; }} }}");
    }
    return string.Join("\n", o) + "\n";
}

static string Arg(string[] args, string name)
{
    var at = Array.IndexOf(args, name);
    return at >= 0 && at + 1 < args.Length ? args[at + 1] : throw new GeneratorError($"{name} <path> is required");
}

static JsonObject AxesBlock(string path)
{
    const string marker = "```json probe-axes";
    var text = File.ReadAllText(path);
    var at = text.IndexOf(marker, StringComparison.Ordinal);
    if (at < 0) throw new GeneratorError($"{path} has no {marker} block");
    var body = text[(at + marker.Length)..];
    return JsonNode.Parse(body[..body.IndexOf("```", StringComparison.Ordinal)]) as JsonObject
           ?? throw new GeneratorError($"the {marker} block of {path} is not a JSON object");
}

static List<string> Values(JsonObject block, string axis) =>
    block["axes"]?[axis] is JsonArray values
        ? [.. values.Select(v => v?.GetValue<string>() ?? throw new GeneratorError($"{axis} holds a null"))]
        : throw new GeneratorError($"the axes file has no axis {axis}");

sealed class GeneratorError(string message) : Exception(message);
