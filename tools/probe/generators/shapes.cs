// Writes tools/probe/corpus/harness/Shapes.g.cs, the probes' shape catalogue: one value object per
// (shape.kind, shape.wrapped) of the axes file, the plain types it wraps, the registry of both, a
// polymorphic base and derived type over each, and the source-generated context ProbeContext.
//
//   dotnet run tools/probe/generators/shapes.cs -- --axes .claude/probe-axes.md --out tools/probe/corpus/harness/Shapes.g.cs
//
// The kinds and wrapped types are the axes file's (its ```json probe-axes block); the C# spelling of each
// wrapped type and its valid and refused samples are the table below, and a value the table does not
// know is refused. GeneratedHarnessTests in the conventions tests holds the committed file to this output.
using System.Text;
using System.Text.Json.Nodes;

try
{
    var axes = AxesBlock(Arg(args, "--axes"));
    var kinds = Values(axes, "shape.kind");
    var wrapped = Values(axes, "shape.wrapped");
    File.WriteAllText(Arg(args, "--out"), Generate(kinds, wrapped), new UTF8Encoding(false));
    return 0;
}
catch (GeneratorError e)
{
    Console.Error.WriteLine($"shapes.cs: {e.Message}");
    return 2;
}

static string Generate(IReadOnlyList<string> kinds, IReadOnlyList<string> wrappedKeys)
{
    var o = new List<string>
    {
        "// <auto-generated/> by tools/probe/generators/shapes.cs; probes' shape catalogue. Do not edit.",
        "#nullable enable\n#pragma warning disable CMTK0014, CS8618, CS1591, CMTK0005, CMTK1000, CMTK0003",
        "using CodoMetis.TypeKit;\nusing CodoMetis.TypeKit.ValueObjects;\nusing CodoMetis.TypeKit.ClosedSets;\nusing System.Text.Json.Serialization;",
        "namespace Probes.Shapes;",
        "public enum PEnum { A, B, C }\n[Flags] public enum PFlags { P = 1, Q = 2, R = 4 }\npublic enum ShapeFault { Refused }",
        "public sealed record PRec { public string A { get; init; } = \"\"; public int B { get; init; } }",
        "public sealed partial class PSet : IClosedSet<PSet> { public static readonly PSet Alpha = new(); public static readonly PSet Beta = new(); }",
    };

    // One value object per kind and wrapped type; the closed set is the one PSet above.
    var entries = new List<(string Kind, string WrappedKey, string Name, Wrapped W)>();
    foreach (var kind in kinds)
    {
        if (kind == "closed-set") continue;
        foreach (var key in wrappedKeys)
        {
            var w = Wrapped.Of(key);
            var n = $"V_{Ident(kind)}_{Ident(key)}";
            o.Add(kind switch
            {
                "record-struct" => $"public readonly partial record struct {n} : IValue<{w.Type}>;",
                "sealed-record-class" => $"public sealed partial record class {n} : IValue<{w.Type}>;",
                "validated-struct" or "validated-class" =>
                    $"public {(kind == "validated-struct" ? "readonly partial record struct" : "sealed partial record class")} {n} : IValidatedValue<{n}, {w.Type}, ShapeFault>\n{{\n" +
                    $"    public static Result<{n}, ShapeFault> Create({w.Type} value) =>\n" +
                    $"        EqualityComparer<{w.Type}>.Default.Equals(value, {w.Refused}) ? Result.Error(ShapeFault.Refused) : new {n}(value);\n}}",
                _ => throw new GeneratorError($"shape.kind {kind} has no declaration here"),
            });
            entries.Add((kind, key, n, w));
        }
    }

    // A polymorphic base and derived type over each value object, PSet, and each plain type.
    foreach (var e in entries) o.Add(Poly(e.Name, e.Name));
    o.Add(Poly("PSet", "PSet"));
    foreach (var key in wrappedKeys)
    {
        var p = Ident(key);
        o.Add($"[JsonPolymorphic] [JsonDerivedType(typeof(PDP_{p}), \"d\")] public abstract class PBP_{p} {{ }}\n" +
              $"public sealed class PDP_{p} : PBP_{p} {{ public {Wrapped.Of(key).Type} Value {{ get; set; }} = default!; }}");
    }
    o.Add("[JsonPolymorphic] [JsonDerivedType(typeof(PDP_string_), \"d\")] public abstract class PBP_string_ { }\n" +
          "public sealed class PDP_string_ : PBP_string_ { public string Value { get; set; } = \"\"; }");

    o.Add("public sealed record Entry(string Kind, string Wrapped, Type Vo, Type Plain, Func<object> Valid, Func<object?> RefusedFn, Type PolyBase, Type PolyDerived, Type PolyBasePlain, Type PolyDerivedPlain);");

    // The registry: a refused sample only where Create refuses one.
    o.Add("public static partial class Registry\n{\n    static partial void Fill(List<Entry> e)\n    {");
    foreach (var (kind, key, n, w) in entries)
    {
        var refused = kind.StartsWith("validated", StringComparison.Ordinal) ? w.Refused : "null";
        o.Add($"        e.Add(new Entry(\"{kind}\", \"{key}\", typeof({n}), typeof({w.Type}), () => {w.Valid}, () => {refused}, " +
              $"typeof(PB_{n}), typeof(PD_{n}), typeof(PBP_{Ident(key)}), typeof(PDP_{Ident(key)})));");
    }
    o.Add("        e.Add(new Entry(\"closed-set\", \"-\", typeof(PSet), typeof(string), () => \"Alpha\", () => null, typeof(PB_PSet), typeof(PD_PSet), typeof(PBP_string_), typeof(PDP_string_)));");
    o.Add("    }\n}");

    // The source-generated context: every value object and plain type as a root and in a class's property.
    o.Add("[JsonSourceGenerationOptions]");
    var seen = new HashSet<string>(StringComparer.Ordinal);
    foreach (var (_, key, n, w) in entries)
    {
        if (key.Contains("Instant", StringComparison.Ordinal)) continue;
        o.Add($"[JsonSerializable(typeof({n}))]");
        o.Add($"[JsonSerializable(typeof(Cn_class_P<{n}>))]");
        if (!seen.Add(w.Type)) continue;
        o.Add($"[JsonSerializable(typeof({w.Type}))]");
        o.Add($"[JsonSerializable(typeof(Cn_class_P<{w.Type}>))]");
        // the wrapped type at a class value object's nullability, for the like-with-like comparison (G1)
        if (w.Type is not ("string" or "Uri" or "System.Uri") && !w.Type.StartsWith('P')) o.Add($"[JsonSerializable(typeof({w.Type}?))]");
    }
    o.Add("[JsonSerializable(typeof(PSet))]\n[JsonSerializable(typeof(Cn_class_P<PSet>))]");
    o.Add("public partial class ProbeContext : JsonSerializerContext { }");

    return string.Join("\n", o) + "\n";
}

static string Poly(string name, string type) =>
    $"[JsonPolymorphic] [JsonDerivedType(typeof(PD_{name}), \"d\")] public abstract class PB_{name} {{ }}\n" +
    $"public sealed class PD_{name} : PB_{name} {{ public {type} Value {{ get; set; }} = default!; }}";

static string Ident(string s) => s.Replace('-', '_').Replace('.', '_');

static string Arg(string[] args, string name)
{
    var at = Array.IndexOf(args, name);
    return at >= 0 && at + 1 < args.Length ? args[at + 1] : throw new GeneratorError($"{name} <path> is required");
}

static JsonObject AxesBlock(string path)
{
    const string marker = "```json probe-axes";
    var text = File.ReadAllText(path);
    var at = text.IndexOf(marker, StringComparison.Ordinal);
    if (at < 0) throw new GeneratorError($"{path} has no {marker} block");
    var body = text[(at + marker.Length)..];
    return JsonNode.Parse(body[..body.IndexOf("```", StringComparison.Ordinal)]) as JsonObject
           ?? throw new GeneratorError($"the {marker} block of {path} is not a JSON object");
}

static List<string> Values(JsonObject block, string axis) =>
    block["axes"]?[axis] is JsonArray values
        ? [.. values.Select(v => v?.GetValue<string>() ?? throw new GeneratorError($"{axis} holds a null"))]
        : throw new GeneratorError($"the axes file has no axis {axis}");

/// <summary>A wrapped type: its C# spelling, a value Create keeps and the one it refuses.</summary>
sealed record Wrapped(string Type, string Valid, string Refused)
{
    static readonly Dictionary<string, Wrapped> Table = new(StringComparer.Ordinal)
    {
        ["string"] = new("string", "\"alpha\"", "\"SECRET-7f3a\""),
        ["Guid"] = new("Guid", "Guid.Parse(\"11111111-1111-1111-1111-111111111111\")", "Guid.Empty"),
        ["int"] = new("int", "42", "-1"),
        ["long"] = new("long", "4200000000L", "-1L"),
        ["byte"] = new("byte", "(byte)7", "(byte)255"),
        ["ulong"] = new("ulong", "4200000000UL", "0UL"),
        ["decimal"] = new("decimal", "7.80m", "-1m"),
        ["double"] = new("double", "1.5", "-1.0"),
        ["bool"] = new("bool", "true", "false"),
        ["char"] = new("char", "'a'", "'x'"),
        ["DateTime"] = new("DateTime", "new DateTime(2026,10,15,8,30,0,DateTimeKind.Utc)", "DateTime.MinValue"),
        ["DateTimeOffset"] = new("DateTimeOffset", "new DateTimeOffset(2026,10,15,8,30,0,TimeSpan.Zero)", "DateTimeOffset.MinValue"),
        ["DateOnly"] = new("DateOnly", "new DateOnly(2026,10,15)", "DateOnly.MinValue"),
        ["TimeOnly"] = new("TimeOnly", "new TimeOnly(8,30,15)", "TimeOnly.MinValue"),
        ["TimeSpan"] = new("TimeSpan", "TimeSpan.FromMinutes(90)", "TimeSpan.MinValue"),
        ["enum"] = new("PEnum", "PEnum.B", "(PEnum)99"),
        ["flags-enum"] = new("PFlags", "PFlags.P | PFlags.Q", "(PFlags)0"),
        ["Uri"] = new("Uri", "new Uri(\"https://example.com/a\")", "new Uri(\"https://example.com/refused\")"),
        ["NodaTime.Instant"] = new("global::NodaTime.Instant", "global::NodaTime.Instant.FromUtc(2026,10,15,8,30)", "global::NodaTime.Instant.MinValue"),
        ["own-record-class"] = new("PRec", "new PRec { A = \"x\", B = 1 }", "new PRec { A = \"refused\", B = 0 }"),
    };

    public static Wrapped Of(string key) =>
        Table.TryGetValue(key, out var w) ? w : throw new GeneratorError($"shape.wrapped {key} is not in shapes.cs's table");
}

sealed class GeneratorError(string message) : Exception(message);
