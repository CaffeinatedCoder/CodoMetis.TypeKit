// Writes tools/probe/corpus/harness/Shapes.g.cs, the probes' shape catalogue: one value object per
// (shape.kind, shape.wrapped) of the axes file, the plain twin each is compared with, the registry of both, a
// polymorphic base and derived type over each, and the source-generated context ProbeContext, which lists every
// type a row holds a value object or its twin in: each shape (a struct one made nullable too, as http.nullability=nullable
// declares it) at each shape.position in each shape.containing, and the
// Option and Result over a value object that L06's rows hold under json.TypeInfoResolver=source-generated-context.
//
// One context, one declaration: System.Text.Json's generator runs once per declaration that carries [JsonSerializable], so
// a second partial part of ProbeContext fails it. L06's carriers are listed from its rows, not for every shape: an Option and
// two Results over every value object at every position would add some 16000 types and three minutes to the Samples' build
// (measured 2026-10-17: 38 s before, 73 s with this context, 3 min 49 s with every carrier at every position).
//
//   dotnet run tools/probe/generators/shapes.cs -- --axes .claude/probe-axes.md --l06 tools/probe/corpus/rows/L06OffTheWireProbe.json.gz \
//       --out tools/probe/corpus/harness/Shapes.g.cs
//
// The kinds, wrapped types, positions and containing types are the axes file's (its ```json probe-axes block); the
// C# spelling of each wrapped type and its valid and refused samples are the table below, and a value the table does
// not know is refused. GeneratedHarnessTests in the conventions tests holds the committed file to this output.
//
// The twin is the wrapped type as the value object holds it, without TypeKit: the same type at the value object's
// nullability. A class value object over a value type admits null where its wrapped struct does not, so its twin is
// the wrapped type made nullable (int? for a sealed record class over int); a struct value object over a value type,
// and any value object over a class, faces the wrapped type itself. A struct value object over a class (string, Uri,
// a record class) refuses a JSON null that its twin reads: no plain type refuses null there, and the claims cite it
// (not-promised a-struct-refuses-a-json-null). The closed set travels as its member's name, so its twin is a string
// (not-promised a-closed-set-is-a-string-enum, a-closed-set-key-is-its-name). The registry's Plain is the twin, and a
// row's position and containing type are put around both alike (harness/Positions.cs, Pos.Twins).
using System.IO.Compression;
using System.Text;
using System.Text.Json.Nodes;

try
{
    var axes = AxesBlock(Arg(args, "--axes"));
    var kinds = Values(axes, "shape.kind");
    var wrapped = Values(axes, "shape.wrapped");
    var positions = Values(axes, "shape.position");
    var containing = Values(axes, "shape.containing");
    var l06 = Rows(Arg(args, "--l06"));
    File.WriteAllText(Arg(args, "--out"), Generate(kinds, wrapped, positions, containing, l06), new UTF8Encoding(false));
    return 0;
}
catch (GeneratorError e)
{
    Console.Error.WriteLine($"shapes.cs: {e.Message}");
    return 2;
}

static string Generate(IReadOnlyList<string> kinds, IReadOnlyList<string> wrappedKeys, IReadOnlyList<string> positions, IReadOnlyList<string> containing, List<Dictionary<string, string>> l06)
{
    var o = new List<string>
    {
        "// <auto-generated/> by tools/probe/generators/shapes.cs; probes' shape catalogue. Do not edit.",
        "#nullable enable\n#pragma warning disable CMTK0014, CS8618, CS1591, CMTK0005, CMTK1000, CMTK0003",
        "using System.Collections.Immutable;\nusing CodoMetis.TypeKit;\nusing CodoMetis.TypeKit.ValueObjects;\nusing CodoMetis.TypeKit.ClosedSets;\nusing System.Text.Json.Serialization;",
        "namespace Probes.Shapes;",
        "public enum PEnum { A, B, C }\n[Flags] public enum PFlags { P = 1, Q = 2, R = 4 }\npublic enum ShapeFault { Refused }",
        "public sealed record PRec { public string A { get; init; } = \"\"; public int B { get; init; } }",
        "public sealed partial class PSet : IClosedSet<PSet> { public static readonly PSet Alpha = new(); public static readonly PSet Beta = new(); }",
    };

    // One value object per kind and wrapped type; the closed set is the one PSet above.
    var entries = new List<(string Kind, string WrappedKey, string Name, Wrapped W, Twin T)>();
    foreach (var kind in kinds)
    {
        if (kind == "closed-set") continue;
        foreach (var key in wrappedKeys)
        {
            var w = Wrapped.Of(key);
            var n = $"V_{Ident(kind)}_{Ident(key)}";
            o.Add(kind switch
            {
                "record-struct" => $"public readonly partial record struct {n} : IValue<{w.Type}>;",
                "sealed-record-class" => $"public sealed partial record class {n} : IValue<{w.Type}>;",
                "validated-struct" or "validated-class" =>
                    $"public {(kind == "validated-struct" ? "readonly partial record struct" : "sealed partial record class")} {n} : IValidatedValue<{n}, {w.Type}, ShapeFault>\n{{\n" +
                    $"    public static Result<{n}, ShapeFault> Create({w.Type} value) =>\n" +
                    $"        EqualityComparer<{w.Type}>.Default.Equals(value, {w.Refused}) ? Result.Error(ShapeFault.Refused) : new {n}(value);\n}}",
                _ => throw new GeneratorError($"shape.kind {kind} has no declaration here"),
            });
            entries.Add((kind, key, n, w, Twin.Of(kind, w)));
        }
    }

    // A polymorphic base and derived type over each value object, PSet, and each twin. Their members are declared as the containers'
    // are (Containers.g.cs), outside the nullable context, so a member admits null by its type alone on both sides, as the twin's
    // nullability says, and json.RespectNullableAnnotations reads no annotation that one side has and the other does not.
    o.Add("#nullable disable");
    foreach (var e in entries) o.Add(Poly(e.Name, e.Name));
    o.Add(Poly("PSet", "PSet"));
    var twins = entries.Select(e => e.T).Append(Twin.ClosedSet).DistinctBy(t => t.Ident).ToList();
    foreach (var t in twins)
        o.Add($"[JsonPolymorphic] [JsonDerivedType(typeof(PDP_{t.Ident}), \"d\")] public abstract class PBP_{t.Ident} {{ }}\n" +
              $"public sealed class PDP_{t.Ident} : PBP_{t.Ident} {{ public {t.Type} Value {{ get; set; }}{t.Initializer} }}");
    o.Add("#nullable enable");

    o.Add("public sealed record Entry(string Kind, string Wrapped, Type Vo, Type Plain, Func<object> Valid, Func<object?> RefusedFn, Type PolyBase, Type PolyDerived, Type PolyBasePlain, Type PolyDerivedPlain);");

    // The registry: a refused sample only where Create refuses one.
    o.Add("public static partial class Registry\n{\n    static partial void Fill(List<Entry> e)\n    {");
    foreach (var (kind, key, n, w, t) in entries)
    {
        var refused = kind.StartsWith("validated", StringComparison.Ordinal) ? w.Refused : "null";
        o.Add($"        e.Add(new Entry(\"{kind}\", \"{key}\", typeof({n}), typeof({t.Type}), () => {w.Valid}, () => {refused}, " +
              $"typeof(PB_{n}), typeof(PD_{n}), typeof(PBP_{t.Ident}), typeof(PDP_{t.Ident})));");
    }
    o.Add($"        e.Add(new Entry(\"closed-set\", \"-\", typeof(PSet), typeof({Twin.ClosedSet.Type}), () => \"Alpha\", () => null, typeof(PB_PSet), typeof(PD_PSet), typeof(PBP_{Twin.ClosedSet.Ident}), typeof(PDP_{Twin.ClosedSet.Ident})));");
    o.Add("    }\n}");

    // The source-generated context: every value object and every twin at every position in every containing type, so a row
    // under json.TypeInfoResolver=source-generated-context runs on the context alone, whatever shape it holds.
    // a struct value object made nullable too: under http.nullability=nullable a row holds V? (and its twin T?) at its position
    var structs = entries.Where(e => e.Kind is "record-struct" or "validated-struct").ToList();
    var members = entries.Select(e => (Type: e.Name, Struct: e.Kind is "record-struct" or "validated-struct", Poly: $"PB_{e.Name}", Key: e.Name))
        .Concat(structs.Select(e => (Type: e.Name + "?", Struct: true, Poly: $"PB_{e.Name}", Key: e.Name)))
        .Append((Type: "PSet", Struct: false, Poly: "PB_PSet", Key: "PSet"))
        .Concat(twins.Select(t => (Type: t.Type, Struct: t.Struct, Poly: $"PBP_{t.Ident}", Key: t.KeyType)))
        .ToList();
    var listed = new List<string>();
    foreach (var m in members)
    {
        listed.Add(m.Type);
        foreach (var position in positions)
            if (position != "root")
                foreach (var c in containing)
                    listed.Add(Holder(position, c, m.Type, m.Struct, m.Poly, m.Key));
    }
    // L06's carriers, as its rows hold them under the context: the Option or Result over the value object, at the row's position in its
    // containing type, its polymorphic stand-in L06's own (JsonFamilyShapes.g.cs, json-family.cs)
    foreach (var r in l06.Where(r => r.GetValueOrDefault("json.TypeInfoResolver") == "source-generated-context"))
    {
        var kind = r["shape.kind"];
        var v = kind == "closed-set" ? "PSet" : entries.FirstOrDefault(e => e.Kind == kind && e.WrappedKey == r["shape.wrapped"]).Name
                ?? throw new GeneratorError($"L06's rows hold {kind} over {r["shape.wrapped"]}, which the axes' shapes do not");
        var (key, carrier) = r["or.shape"] switch
        {
            "Option" => ("O", $"Option<{v}>"),
            "Result-T-E" or "Task-of-Result" or "ValueTask-of-Result" => ("RTE", $"Result<{v}, ShapeFault>"),
            "Result-E" => ("RE", $"Result<{v}>"),
            var shape => throw new GeneratorError($"or.shape {shape} has no carrier here"),
        };
        var position = r["shape.position"];
        listed.Add(position == "root" ? carrier : Holder(position, r["shape.containing"], carrier, true, $"global::Probes.Json.L06PB_{v}_{key}", carrier));
    }
    o.Add("[JsonSourceGenerationOptions]");
    var i = 0;
    foreach (var t in listed.Distinct(StringComparer.Ordinal))
        // a generic, array or nullable type gets a name of its own (two would collide); a plain type keeps the serializer's
        o.Add(t.Contains('<') || t.Contains('[') || t.EndsWith('?') ? $"[JsonSerializable(typeof({t}), TypeInfoPropertyName = \"T{i++}\")]" : $"[JsonSerializable(typeof({t}))]");
    o.Add("public partial class ProbeContext : JsonSerializerContext { }");

    return string.Join("\n", o) + "\n";
}

static string Poly(string name, string type) =>
    $"[JsonPolymorphic] [JsonDerivedType(typeof(PD_{name}), \"d\")] public abstract class PB_{name} {{ }}\n" +
    $"public sealed class PD_{name} : PB_{name} {{ public {type} Value {{ get; set; }} = default!; }}";

// The type a row's position holds m in, as harness/Positions.cs builds it: m itself at the root, else a container of
// Containers.g.cs around m, its list, array, dictionary, patch or polymorphic base. A dictionary key is never null, nor is
// what a Patch<T> holds (T : notnull), so there a nullable twin is the type it holds (key).
static string Holder(string position, string containing, string m, bool isStruct, string polyBase, string key)
{
    var style = position switch { "field" => "F", "record-ctor-parameter" => "C", "required-init" => "R", _ => "P" };
    var member = position switch
    {
        "property" or "field" or "record-ctor-parameter" or "required-init" => m,
        "nullable-property" => isStruct && !m.EndsWith('?') ? m + "?" : m,
        "list-element" => $"List<{m}>",
        "read-only-list-element" => $"IReadOnlyList<{m}>",
        "array-element" => $"{m}[]",
        "immutable-array-element" => $"ImmutableArray<{m}>",
        "dictionary-key" => $"Dictionary<{key}, int>",
        "dictionary-value" => $"Dictionary<string, {m}>",
        "in-patch" => $"Patch<{key}>",
        "polymorphic-derived-property" => polyBase,
        _ => throw new GeneratorError($"shape.position {position} has no holder here"),
    };
    var n = containing switch
    {
        "class" or "record-class" or "struct" or "record-struct" or "generic-type" => containing.Replace('-', '_'),
        _ => throw new GeneratorError($"shape.containing {containing} has no holder here"),
    };
    return containing == "generic-type" ? $"Cn_{n}_{style}<{member}, int>" : $"Cn_{n}_{style}<{member}>";
}

static string Ident(string s) => s.Replace('-', '_').Replace('.', '_');

// A rows file of `prober rows`: gzipped JSON, {"claim": ..., "rows": [{"row": {axis: value}}, ...]}.
static List<Dictionary<string, string>> Rows(string path)
{
    using var gzip = new GZipStream(File.OpenRead(path), CompressionMode.Decompress);
    var rows = JsonNode.Parse(gzip)?["rows"] as JsonArray ?? throw new GeneratorError($"{path} has no rows");
    return
    [
        .. rows.Select(r => (r?["row"] as JsonObject ?? throw new GeneratorError($"{path}: an entry without a row"))
                   .ToDictionary(p => p.Key, p => p.Value?.GetValue<string>() ?? throw new GeneratorError($"{path}: {p.Key} is null"), StringComparer.Ordinal)),
    ];
}

static string Arg(string[] args, string name)
{
    var at = Array.IndexOf(args, name);
    return at >= 0 && at + 1 < args.Length ? args[at + 1] : throw new GeneratorError($"{name} <path> is required");
}

static JsonObject AxesBlock(string path)
{
    const string marker = "```json probe-axes";
    var text = File.ReadAllText(path);
    var at = text.IndexOf(marker, StringComparison.Ordinal);
    if (at < 0) throw new GeneratorError($"{path} has no {marker} block");
    var body = text[(at + marker.Length)..];
    return JsonNode.Parse(body[..body.IndexOf("```", StringComparison.Ordinal)]) as JsonObject
           ?? throw new GeneratorError($"the {marker} block of {path} is not a JSON object");
}

static List<string> Values(JsonObject block, string axis) =>
    block["axes"]?[axis] is JsonArray values
        ? [.. values.Select(v => v?.GetValue<string>() ?? throw new GeneratorError($"{axis} holds a null"))]
        : throw new GeneratorError($"the axes file has no axis {axis}");

/// <summary>A wrapped type: its C# spelling, a value Create keeps and the one it refuses.</summary>
sealed record Wrapped(string Key, string Type, string Valid, string Refused)
{
    static readonly Dictionary<string, Wrapped> Table = new(StringComparer.Ordinal)
    {
        ["string"] = new("", "string", "\"alpha\"", "\"SECRET-7f3a\""),
        ["Guid"] = new("", "Guid", "Guid.Parse(\"11111111-1111-1111-1111-111111111111\")", "Guid.Empty"),
        ["int"] = new("", "int", "42", "-1"),
        ["long"] = new("", "long", "4200000000L", "-1L"),
        ["byte"] = new("", "byte", "(byte)7", "(byte)255"),
        ["ulong"] = new("", "ulong", "4200000000UL", "0UL"),
        ["decimal"] = new("", "decimal", "7.80m", "-1m"),
        ["double"] = new("", "double", "1.5", "-1.0"),
        ["bool"] = new("", "bool", "true", "false"),
        ["char"] = new("", "char", "'a'", "'x'"),
        ["DateTime"] = new("", "DateTime", "new DateTime(2026,10,15,8,30,0,DateTimeKind.Utc)", "DateTime.MinValue"),
        ["DateTimeOffset"] = new("", "DateTimeOffset", "new DateTimeOffset(2026,10,15,8,30,0,TimeSpan.Zero)", "DateTimeOffset.MinValue"),
        ["DateOnly"] = new("", "DateOnly", "new DateOnly(2026,10,15)", "DateOnly.MinValue"),
        ["TimeOnly"] = new("", "TimeOnly", "new TimeOnly(8,30,15)", "TimeOnly.MinValue"),
        ["TimeSpan"] = new("", "TimeSpan", "TimeSpan.FromMinutes(90)", "TimeSpan.MinValue"),
        ["enum"] = new("", "PEnum", "PEnum.B", "(PEnum)99"),
        ["flags-enum"] = new("", "PFlags", "PFlags.P | PFlags.Q", "(PFlags)0"),
        ["Uri"] = new("", "Uri", "new Uri(\"https://example.com/a\")", "new Uri(\"https://example.com/refused\")"),
        ["NodaTime.Instant"] = new("", "global::NodaTime.Instant", "global::NodaTime.Instant.FromUtc(2026,10,15,8,30)", "global::NodaTime.Instant.MinValue"),
        ["own-record-class"] = new("", "PRec", "new PRec { A = \"x\", B = 1 }", "new PRec { A = \"refused\", B = 0 }"),
    };

    public static Wrapped Of(string key) =>
        Table.TryGetValue(key, out var w) ? w with { Key = key } : throw new GeneratorError($"shape.wrapped {key} is not in shapes.cs's table");
}

/// <summary>
/// A value object's twin: the wrapped type at the value object's nullability (see the head of this file), its identifier in
/// the stand-ins' names, whether it is a struct, the type a dictionary key of it is, and its stand-in's initializer.
/// </summary>
sealed record Twin(string Type, string Ident, bool Struct, string KeyType, string Initializer)
{
    static readonly HashSet<string> Classes = new(StringComparer.Ordinal) { "string", "Uri", "PRec" };

    /// <summary>The closed set's twin: the member's name, a string.</summary>
    public static readonly Twin ClosedSet = new("string", "string_", false, "string", " = \"\";");

    public static Twin Of(string kind, Wrapped w)
    {
        var valueType = !Classes.Contains(w.Type);
        var classVo = kind is "sealed-record-class" or "validated-class";
        var ident = w.Key.Replace('-', '_').Replace('.', '_');
        return valueType && classVo
            ? new($"{w.Type}?", ident + "_N", true, w.Type, "")
            : new(w.Type, ident, valueType, w.Type, " = default!;");
    }
}

sealed class GeneratorError(string message) : Exception(message);
