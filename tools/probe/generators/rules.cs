// Writes tools/probe/corpus/harness/RuleControllers.g.cs: the MVC controllers C03 and C05 run against, one action per
// arity (a Fault of two or three sets) and response variant, routed c/{arity}/{variant}, each answering Cmp's errors.
// The variants are those ComposedClaims.Variant names a row's http.response by and Cmp.MapMinimal maps on the minimal
// side; the class names are what ComposedClaims hands the host (RuleApiController, RulePlainController).
//
//   dotnet run tools/probe/generators/rules.cs -- --out tools/probe/corpus/harness/RuleControllers.g.cs
//
// GeneratedHarnessTests in the conventions tests holds the committed file to this output.
using System.Text;

try
{
    File.WriteAllText(Arg(args, "--out"), Generate(), new UTF8Encoding(false));
    return 0;
}
catch (GeneratorError e)
{
    Console.Error.WriteLine($"rules.cs: {e.Message}");
    return 2;
}

static string Generate()
{
    // variant: the attribute it adds to the action (Cmp.Decorate's, as MVC declares it), and whether it answers KFault,
    // whose Clash shares HFault's name, in place of GFault
    (string Name, string Attribute, bool SameName)[] variants =
    [
        ("plain", "", false),
        ("wo", ", WithoutFaults<HFault>(nameof(HFault.Bad))", false),
        ("group", ", FaultStatus<HFault>(nameof(HFault.Clash), 422)", false),
        ("declared", ", ProducesResponseType<ProblemDetails>(429)", false),
        ("dup", "", true),
    ];
    var o = new List<string>
    {
        "// Generated by tools/probe/generators/rules.cs: controllers answering composed faults, one action per arity x response variant (C03, C05).",
        "using CodoMetis.TypeKit;",
        "using CodoMetis.TypeKit.AspNetCore;",
        "using Microsoft.AspNetCore.Http.HttpResults;",
        "using Microsoft.AspNetCore.Http;",
        "using Microsoft.AspNetCore.Mvc;",
        "namespace Probes;",
        "public abstract class RuleCtlBase : ControllerBase",
        "{",
    };
    foreach (var (name, attribute, sameName) in variants)
    {
        foreach (var arity in new[] { 2, 3 })
        {
            var second = sameName ? "KFault" : "GFault";
            var faults = $"FaultProblem<HFault>, FaultProblem<{second}>" + (arity == 3 ? ", FaultProblem<SFault>" : "");
            var method = (arity == 2 ? "Two" : "Three") + (sameName ? "K" : "");
            o.Add($"    [HttpGet(\"c/{arity}/{name}\"){attribute}]");
            o.Add($"    public Results<NoContent, {faults}> A{arity}{char.ToUpperInvariant(name[0])}{name[1..]}(int e) => Cmp.{method}(e).ToHttpResult();");
        }
    }
    o.Add("}");
    o.Add("[ApiController] public sealed class RuleApiController : RuleCtlBase { }");
    o.Add("public sealed class RulePlainController : RuleCtlBase { }");
    return string.Join("\n", o) + "\n";
}

static string Arg(string[] args, string name)
{
    var at = Array.IndexOf(args, name);
    return at >= 0 && at + 1 < args.Length ? args[at + 1] : throw new GeneratorError($"{name} <path> is required");
}

sealed class GeneratorError(string message) : Exception(message);
