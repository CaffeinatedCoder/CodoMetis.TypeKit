// sample: ef-core/types
public readonly partial record struct InvoiceNo : IValue<long>;

public readonly partial record struct CustomerId : IValue<Guid>;

public readonly partial record struct Amount : IValue<decimal>;

public readonly partial record struct Currency : IValue<string>;

public readonly partial record struct IssuedOn : IValue<DateOnly>;

public readonly partial record struct Discount : IValue<int>;

public enum ReferenceFault { Blank, NotUpperCase }

public readonly partial record struct Reference : IValidatedValue<Reference, string, ReferenceFault>
{
    public static Result<Reference, ReferenceFault> Create(string value)
    {
        if (string.IsNullOrWhiteSpace(value)) return Result.Error(ReferenceFault.Blank);
        if (value != value.ToUpperInvariant()) return Result.Error(ReferenceFault.NotUpperCase);   // a rule added after rows were written

        return new Reference(value);
    }
}
// end sample

// sample: ef-core/model
public class Invoice
{
#pragma warning disable CMTK0006 // the database assigns the key on insert
    public InvoiceNo No { get; set; }                      // key: bigint, generated by the database
#pragma warning restore CMTK0006
    public required CustomerId Customer { get; set; }      // uuid
    public required Reference Reference { get; set; }      // text, applies Create on input and is read back without it
    public required Amount Total { get; set; }             // numeric(18,2), from ConfigureConventions
    public required Currency Currency { get; set; }        // character varying(3), from ConfigureConventions
    public required IssuedOn IssuedOn { get; set; }        // date
    public Discount? Discount { get; set; }                // integer, nullable
}

public sealed class BillingDb(DbContextOptions<BillingDb> options) : DbContext(options)
{
    public DbSet<Invoice> Invoices => Set<Invoice>();

    protected override void ConfigureConventions(ModelConfigurationBuilder builder)
    {
        builder.Properties<Amount>().HavePrecision(18, 2);   // by the value object's type: EF applies a convention by CLR type, so Properties<decimal>() would miss it
        builder.Properties<Currency>().HaveMaxLength(3);
    }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<Invoice>().HasKey(invoice => invoice.No);
        modelBuilder.Entity<Invoice>().HasData(new Invoice   // seed data takes value objects as it takes primitives
        {
            No = InvoiceNo.From(1),
            Customer = CustomerId.From(Guid.Parse("0199aaaa-bbbb-7ccc-8ddd-eeeeeeeeeeee")),
            Reference = Reference.FromKnownGood("INV-1"),
            Total = Amount.From(10m),
            Currency = Currency.From("EUR"),
            IssuedOn = IssuedOn.From(new DateOnly(2026, 1, 1)),
        });
    }
}
// end sample

public static class Usage
{
    public static async Task<(long Assigned, string Verdict, string Stored, Option<Discount> DiscountRead)> WalkthroughAsync()
    {
        // sample: ef-core/keys
        await using var connection = new SqliteConnection("Data Source=:memory:");   // one connection keeps the in-memory database alive
        await connection.OpenAsync();
        await using var db = new BillingDb(new DbContextOptionsBuilder<BillingDb>().UseSqlite(connection).UseTypeKit().Options);
        await db.Database.EnsureCreatedAsync();

        var invoice = new Invoice
        {
            Customer = CustomerId.New(),
            Reference = Reference.FromKnownGood("INV-2"),
            Total = Amount.From(250m),
            Currency = Currency.From("EUR"),
            IssuedOn = IssuedOn.From(new DateOnly(2026, 10, 13)),
        };
        db.Invoices.Add(invoice);
        await db.SaveChangesAsync();

        long assigned = invoice.No.Value;   // 2, assigned by the database; the seeded invoice is 1
        // end sample

        // sample: ef-core/reading-back
        await db.Database.ExecuteSqlAsync($"UPDATE Invoices SET Reference = 'inv-2' WHERE No = 2");   // a row from before the upper-case rule
        db.ChangeTracker.Clear();

        var read = await db.Invoices.SingleAsync(i => i.No == InvoiceNo.From(2));                         // maps, without Create
        string verdict = read.Reference.Revalidate().Match(_ => "valid", fault => $"refused: {fault}");   // "refused: NotUpperCase"
        string stored = read.Reference.Value;                                                             // "inv-2", as the row holds it
        // end sample

        // sample: ef-core/option
        Option<Discount> discount = read.Discount.ToOption();   // None
        // end sample

        return (assigned, verdict, stored, discount);
    }

    public static void Queries(BillingDb db, Currency eur, List<CustomerId> customers)
    {
        // sample: ef-core/queries
        db.Invoices.Where(i => i.Total.Value >= 100m && i.Currency == eur);          // WHERE i."Total" >= 100.0 AND i."Currency" = @eur
        db.Invoices.Where(i => i.Reference.Value.EndsWith("-1"));                      // WHERE i."Reference" LIKE '%-1'
        db.Invoices.Where(i => i.IssuedOn.Value.Year == 2026);                          // WHERE date_part('year', i."IssuedOn")::int = 2026
        db.Invoices.Where(i => i.Discount.ValueOrNull() == null);                       // WHERE i."Discount" IS NULL
        db.Invoices.Where(i => customers.Contains(i.Customer));                         // WHERE i."Customer" = ANY (@customers)
        db.Invoices.OrderByDescending(i => i.IssuedOn).ThenBy(i => i.No);
        db.Invoices.Select(i => new { i.No, Total = i.Total.Value });                   // the wrapped value projected
        db.Invoices.GroupBy(i => i.Currency).Select(g => new { Currency = g.Key, Sum = g.Sum(i => i.Total.Value) });   // an aggregate over the column
        // end sample
    }
}

public sealed class EfCoreTests
{
    private const string Readme = "docs/ef-core.md";

    /// <summary>Each property's comment in the model sample names what the model maps it to on PostgreSQL.</summary>
    [Fact]
    public void The_columns_are_what_the_model_s_comments_say()
    {
        using var db = new BillingDb(SampleOutputs.NpgsqlWithoutServer<BillingDb>());
        var invoice = db.Model.FindEntityType(typeof(Invoice))!;
        var comments = SampleOutputs.PropertyComments(Readme, "public class Invoice");
        IProperty Property(string name) => invoice.FindProperty(name)!;

        comments.Keys.ShouldBe(invoice.GetProperties().Select(property => property.Name), ignoreOrder: true);

        invoice.FindPrimaryKey()!.Properties.ShouldBe([Property(nameof(Invoice.No))]);
        Property(nameof(Invoice.No)).ValueGenerated.ShouldBe(ValueGenerated.OnAdd);
        comments[nameof(Invoice.No)].ShouldBe($"key: {Property(nameof(Invoice.No)).GetColumnType()}, generated by the database");
        comments[nameof(Invoice.Customer)].ShouldBe(Property(nameof(Invoice.Customer)).GetColumnType());
        comments[nameof(Invoice.Reference)].ShouldStartWith($"{Property(nameof(Invoice.Reference)).GetColumnType()}, ");
        comments[nameof(Invoice.Total)].ShouldStartWith($"{Property(nameof(Invoice.Total)).GetColumnType()}, ");
        comments[nameof(Invoice.Currency)].ShouldStartWith($"{Property(nameof(Invoice.Currency)).GetColumnType()}, ");
        comments[nameof(Invoice.IssuedOn)].ShouldBe(Property(nameof(Invoice.IssuedOn)).GetColumnType());
        Property(nameof(Invoice.Discount)).IsNullable.ShouldBeTrue();
        comments[nameof(Invoice.Discount)].ShouldBe($"{Property(nameof(Invoice.Discount)).GetColumnType()}, nullable");
    }

    [Fact]
    public void The_queries_are_the_SQL_the_comments_say()
    {
        using var db = new BillingDb(SampleOutputs.NpgsqlWithoutServer<BillingDb>());
        var eur = Currency.From("EUR");
        List<CustomerId> customers = [CustomerId.New()];

        db.Invoices.Where(i => i.Total.Value >= 100m && i.Currency == eur).ShouldBeTheSqlShownIn(Readme);
        db.Invoices.Where(i => i.Reference.Value.EndsWith("-1")).ShouldBeTheSqlShownIn(Readme);
        db.Invoices.Where(i => i.IssuedOn.Value.Year == 2026).ShouldBeTheSqlShownIn(Readme);
        db.Invoices.Where(i => i.Discount.ValueOrNull() == null).ShouldBeTheSqlShownIn(Readme);
        db.Invoices.Where(i => customers.Contains(i.Customer)).ShouldBeTheSqlShownIn(Readme);
        db.Invoices.OrderByDescending(i => i.IssuedOn).ThenBy(i => i.No).ToQueryString().ShouldContain("ORDER BY i.\"IssuedOn\" DESC, i.\"No\"");
        db.Invoices.Select(i => new { i.No, Total = i.Total.Value }).ToQueryString().ShouldContain("SELECT i.\"No\", i.\"Total\"");
        db.Invoices.GroupBy(i => i.Currency).Select(g => new { Currency = g.Key, Sum = g.Sum(i => i.Total.Value) }).ToQueryString().ShouldContain("sum(i.\"Total\")");
        Usage.Queries(db, eur, customers);
    }

    [Fact]
    public async Task The_walkthrough_answers_what_the_comments_say()
    {
        var (assigned, verdict, stored, discount) = await Usage.WalkthroughAsync();

        assigned.ShouldBeShownIn(Readme, value => value.ToString(), "invoice.No.Value");
        verdict.ShouldBeShownIn(Readme, text => $"\"{text}\"", "read.Reference.Revalidate().Match(_ => \"valid\", fault => $\"refused: {fault}\")");
        stored.ShouldBeShownIn(Readme, text => $"\"{text}\"", "read.Reference.Value");
        discount.ShouldBeShownIn(Readme, option => option.IsNone() ? "None" : "Some", "read.Discount.ToOption()");
    }

    [Fact]
    public async Task The_seed_is_written_with_the_schema()
    {
        await using var connection = new SqliteConnection("Data Source=:memory:");
        await connection.OpenAsync(TestContext.Current.CancellationToken);
        await using var db = new BillingDb(new DbContextOptionsBuilder<BillingDb>().UseSqlite(connection).UseTypeKit().Options);
        await db.Database.EnsureCreatedAsync(TestContext.Current.CancellationToken);

        var seeded = await db.Invoices.SingleAsync(TestContext.Current.CancellationToken);
        (seeded.No, seeded.Reference, seeded.Total, seeded.Currency).ShouldBe((InvoiceNo.From(1), Reference.FromKnownGood("INV-1"), Amount.From(10m), Currency.From("EUR")));
    }
}
