using Microsoft.EntityFrameworkCore;
using Npgsql;

namespace CodoMetis.TypeKit.Facts;

/// <summary>
/// design/knowledge/KB-036: Npgsql's EF provider declares a plain <see cref="char"/> key an identity column of
/// <c>character(1)</c>, which PostgreSQL refuses: an identity column's type must be <c>smallint</c>, <c>integer</c>
/// or <c>bigint</c>.
/// </summary>
public sealed class KB036
{
    public sealed class CharKey
    {
        public char Id { get; set; }

        public string N { get; set; } = "";
    }

    [Fact]
    public async Task A_char_key_gets_an_identity_column_PostgreSQL_refuses()
    {
        await using var db = await Pg.ContextAsync(model => model.Entity<CharKey>(), create: false);

        db.Database.GenerateCreateScript().ShouldContain("\"Id\" character(1) GENERATED BY DEFAULT AS IDENTITY");
        var refused = await Should.ThrowAsync<PostgresException>(() => db.Database.EnsureCreatedAsync(TestContext.Current.CancellationToken));
        refused.SqlState.ShouldBe("22023", "identity column type must be smallint, integer, or bigint");
    }
}
